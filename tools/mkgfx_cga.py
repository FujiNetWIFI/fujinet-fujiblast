#!/usr/bin/env python3
"""mkgfx_cga.py -- gfx/cga/*.png and gfx/namco.bin -> the MS-DOS port's data.

    python3 tools/mkgfx_cga.py OUTDIR    # writes OUTDIR/gfxdata.c, gfxcodes.h

CGA's 320x200 mode: 2 bits a pixel, 4 pixels a byte, the leftmost in the
top bits. Everything here is in that form, a line's bytes left to right:
  tile_gfx    tile frames, 16 lines of 4 bytes
  tile_anim   per tile, the frame for each of the 4 animation phases
  cell_gfx    the arena's wall and the side panels: 8 lines of 2 bytes
  logo_gfx    24 lines of 54 bytes (216 pixels)
  spr_role    sprite frames, 16 lines of 4 bytes, in roles (0 eyes, 1 body,
              2 trim, 3 visor; 0 where clear); src/msdos/gfx.c colours them
              for the seat
  spr_mask    the same frames' masks: 11 where clear (the background kept)
  font_gfx    the Namco font, ASCII 32-127, 8 bytes a glyph, bit 7 left
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from artlayout import TILES, SPRITES  # noqa: E402
from png import Image  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
CGA = os.path.join(ROOT, "gfx", "cga")

# drawart_cga.py's key: the pixel values in mode 5's colours on black
KEY = {(0x00, 0x00, 0x00): 0, (0x55, 0xFF, 0xFF): 1, (0xFF, 0x55, 0x55): 2, (0xFF, 0xFF, 0xFF): 3}
ROLE = {(255, 255, 255): 1, (255, 85, 85): 2, (85, 255, 255): 3, (0, 0, 0): 0}
POWERUPS = ("fire", "bombup", "speed", "kick", "glove")


def pixels(img, x0, y0, w, h):
    out = []
    for y in range(h):
        row = []
        for x in range(w):
            p = img.getpixel((x0 + x, y0 + y))
            if p[:3] not in KEY:
                raise ValueError(f"({x0 + x},{y0 + y}): {p} is not a sheet colour")
            row.append(KEY[p[:3]])
        out.append(row)
    return out


def pack(row):
    """Pixel values (a multiple of 4) -> bytes, the left pixel on top."""
    out = []
    for i in range(0, len(row), 4):
        b = 0
        for p in row[i:i + 4]:
            b = b << 2 | p
        out.append(b)
    return out


def tiles():
    img = Image(os.path.join(CGA, "tiles.png"))
    frames, anim = [], []
    for i, name in enumerate(TILES):
        mine = []
        for f in range(4):
            px = pixels(img, f * 16, i * 16, 16, 16)
            if f and not any(any(r) for r in px):
                break               # an empty column: no more frames
            mine.append(len(frames))
            frames.append([b for r in px for b in pack(r)])
        n = len(mine)
        if n == 1:
            order = [0, 0, 0, 0]
        elif n == 2:
            order = [0, 0, 1, 1] if name in POWERUPS else [0, 1, 0, 1]
        elif n == 4:
            order = [0, 1, 2, 3]
        else:
            raise ValueError(f"{name}: {n} frames")
        anim.append([mine[k] for k in order])
    return frames, anim


def cells():
    img = Image(os.path.join(CGA, "cells.png"))
    return [[b for r in pixels(img, i * 8, 0, 8, 8) for b in pack(r)] for i in range(2)]


def logo():
    img = Image(os.path.join(CGA, "logo.png"))
    assert img.width == 216 and img.height == 24, (img.width, img.height)
    return [pack(r) for r in pixels(img, 0, 0, 216, 24)]


def sprites():
    img = Image(os.path.join(CGA, "sprites.png"))
    roles, masks = [], []
    for i in range(len(SPRITES)):
        role, mask = [], []
        for y in range(16):
            rr, mm = [], []
            for x in range(16):
                p = img.getpixel((i * 16 + x, y))
                if p[3] < 128:
                    rr.append(0)
                    mm.append(3)
                else:
                    if p[:3] not in ROLE:
                        raise ValueError(f"sprite {SPRITES[i]} ({x},{y}): {p}")
                    rr.append(ROLE[p[:3]])
                    mm.append(0)
            role += pack(rr)
            mask += pack(mm)
        roles.append(role)
        masks.append(mask)
    return roles, masks


def carray(name, rows, per_line=16):
    out = [f"const uint8_t {name} = {{"]
    for r in rows:
        out.append("    { " + ", ".join(f"0x{b:02X}" for b in r) + " },")
    out.append("};")
    return "\n".join(out)


def flat(name, data):
    out = [f"const uint8_t {name} = {{"]
    for i in range(0, len(data), 16):
        out.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    out.append("};")
    return "\n".join(out)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "gen", "msdos")
    os.makedirs(out, exist_ok=True)
    frames, anim = tiles()
    cell = cells()
    lg = logo()
    roles, masks = sprites()
    font = open(os.path.join(ROOT, "gfx", "namco.bin"), "rb").read()
    assert len(font) == 768

    h = ["/* GENERATED by tools/mkgfx_cga.py from gfx/cga/*.png: do not edit. */",
         "#ifndef GFXCODES_H", "#define GFXCODES_H", "#include <stdint.h>", ""]
    for i, name in enumerate(SPRITES):
        h.append(f"#define FR_{name.upper():8s} {i}")
    h += ["",
          f"#define N_SPR_FRAMES {len(SPRITES)}",
          f"#define N_TFRAMES    {len(frames)}",
          f"#define T_TROPHY     {TILES.index('trophy')}",
          f"#define N_TGFX       {len(TILES)}",
          "#define CELL_WALL    0",
          "#define CELL_PANEL   1",
          "#define LOGO_BYTES   54",
          "#define LOGO_LINES   24",
          "",
          "extern const uint8_t tile_gfx[N_TFRAMES][64];",
          "extern const uint8_t tile_anim[N_TGFX][4];",
          "extern const uint8_t cell_gfx[2][16];",
          "extern const uint8_t logo_gfx[LOGO_LINES][LOGO_BYTES];",
          "extern const uint8_t spr_role[N_SPR_FRAMES][64];",
          "extern const uint8_t spr_mask[N_SPR_FRAMES][64];",
          "extern const uint8_t font_gfx[768];",
          "", "#endif", ""]
    open(os.path.join(out, "gfxcodes.h"), "w").write("\n".join(h))

    c = ["/* GENERATED by tools/mkgfx_cga.py from gfx/cga/*.png and gfx/namco.bin: do not edit. */",
         "#include <stdint.h>", '#include "gfxcodes.h"', "",
         carray("tile_gfx[N_TFRAMES][64]", frames), "",
         carray("tile_anim[N_TGFX][4]", anim), "",
         carray("cell_gfx[2][16]", cell), "",
         carray("logo_gfx[LOGO_LINES][LOGO_BYTES]", lg), "",
         carray("spr_role[N_SPR_FRAMES][64]", roles), "",
         carray("spr_mask[N_SPR_FRAMES][64]", masks), "",
         flat("font_gfx[768]", font), ""]
    open(os.path.join(out, "gfxdata.c"), "w").write("\n".join(c))
    print(f"{out}: {len(frames)} tile frames, {len(SPRITES)} sprite frames")


if __name__ == "__main__":
    main()
