#!/usr/bin/env python3
"""mkgfx_intv.py -- gfx/intv/*.png (tools/drawart_intv.py's) into
gen/intv/gfx.bas for src/intv: the GRAM cards (IntyBASIC DEFINE's form:
4 words a card, two rows a word, the first in the low byte), each tile's
card word, the BACKTAB address of each arena tile, and the bombers'
frames.

GRAM (tools/artlayout_intv.py):
  0-17   the bodies, 2 cards each (DOUBLEY: 16 rows in a card's height)
  18-20  the visors
  22-44  the arena: pillar, block, the 15 animated (4 pages), the bomb's
         halves, wall, trophy
  22-57  the title's logo instead (a letter 2x2 cards)

usage: mkgfx_intv.py gen/intv"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import png  # noqa: E402
from artlayout_intv import (PAL, TILES, ANIM, G_TILE0, BODIES, VISORS, LOGO_TEXT, FLOOR, DUD_FG,  # noqa: E402
                            SEAT_BODY, VISOR, LOGO_TOP, LOGO_BOTTOM, BLACK)

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
ARENA_W, ARENA_H = 13, 11
AR_COL, AR_ROW = 4, 1

# proto.h's tiles, in order, and the sheet's names for them
T_NAMES = ["floor", "pillar", "block", "burn", "bomb", "dud", "flameC", "flameH", "flameV", "flameL", "flameR",
           "flameU", "flameD", "fire", "bombup", "speed", "kick", "glove"]
# artlayout.SPRITES' frames (gfxcodes FR_*): body, flipped, visor, its rows down
FRAMES = [("down0", 0, "front", 2), ("down1", 0, "front", 2), ("down1", 1, "front", 2),
          ("down0", 0, None, 0), ("down1", 0, None, 0), ("down1", 1, None, 0),
          ("right0", 0, "side", 2), ("right1", 0, "side", 2), ("right2", 0, "side", 2),
          ("right0", 1, "side", 2), ("right1", 1, "side", 2), ("right2", 1, "side", 2),
          ("win0", 0, "front", 2), ("win1", 0, "frontlo", 2),
          ("down0", 0, None, 0), ("right0", 1, "side", 2), ("die2", 0, "front", 3), ("die3", 0, None, 0)]
FR_NAMES = ["DOWN0", "DOWN1", "DOWN2", "UP0", "UP1", "UP2", "RIGHT0", "RIGHT1", "RIGHT2", "LEFT0", "LEFT1",
            "LEFT2", "WIN0", "WIN1", "DIE0", "DIE1", "DIE2", "DIE3"]


def fgbg(fg, bg):
    return fg | (bg & 3) << 9 | (bg & 4) << 11 | (bg & 8) << 9


def mobcol(c):
    return (c & 7) | (c & 8) << 9


def card_rows(img, x0, y0, on):
    """8 rows of a card: a pixel is 1 if on(rgb)."""
    return [sum(1 << (7 - x) for x in range(8) if on(img.getpixel((x0 + x, y0 + y))[:3])) for y in range(8)]


def words(rows):
    return [rows[i] | rows[i + 1] << 8 for i in range(0, 8, 2)]


def data(f, label, cards):
    f.write("%s:\n" % label)
    for c in cards:
        f.write("    DATA %s\n" % ", ".join("$%04X" % w for w in words(c)))


def main():
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    gfx = os.path.join(ROOT, "gfx", "intv")
    tiles = png.Image(os.path.join(gfx, "tiles.png"))
    sprites = png.Image(os.path.join(gfx, "sprites.png"))
    logo = png.Image(os.path.join(gfx, "logo.png"))
    colours = {name: (fg, bg) for name, fg, bg in TILES}
    row_of = {name: i for i, (name, _, _) in enumerate(TILES)}

    def tile(name, frame):
        fg, _ = colours[name]
        return card_rows(tiles, frame * 8, row_of[name] * 8, lambda p: p == PAL[fg])

    # the arena's GRAM: G_TILE0 on
    order = ["pillar", "block"] + ANIM + ["halfL", "halfR", "halfU", "halfD", "wall", "trophy"]
    gcard = {n: G_TILE0 + i for i, n in enumerate(order)}

    def word(name):
        fg, bg = colours[name]
        return 0x800 | gcard[name] << 3 | fgbg(fg, bg)

    tword = [fgbg(BLACK, FLOOR)] + [word(n) for n in T_NAMES[1:]]

    body = {}
    for i, k in enumerate(BODIES):
        top = card_rows(sprites, i * 8, 0, lambda p: p != (0, 0, 0))
        bot = card_rows(sprites, i * 8, 8, lambda p: p != (0, 0, 0))
        body[k] = (top, bot)
    nb = len(BODIES)
    visor = {k: card_rows(sprites, (nb + i) * 8, 0, lambda p: p != (0, 0, 0)) for i, k in enumerate(VISORS)}
    vcard = {k: 2 * nb + i for i, k in enumerate(VISORS)}

    tpos = [0x200 + (AR_ROW + r) * 20 + AR_COL + c for r in range(ARENA_H) for c in range(ARENA_W)]

    with open(os.path.join(out, "gfx.bas"), "w") as f:
        f.write("' GENERATED by tools/mkgfx_intv.py from gfx/intv/*.png: do not edit.\n\n")
        f.write("    CONST G_TILE0 = %d\n" % G_TILE0)
        for n in order:
            f.write("    CONST G_%s = %d\n" % (n.upper(), gcard[n]))
        f.write("    CONST G_ANIM = %d\n    CONST N_ANIM = %d\n" % (gcard[ANIM[0]], len(ANIM)))
        f.write("    CONST G_LOGO = %d\n" % G_TILE0)
        f.write("    CONST CW_FLOOR = $%04X\n" % tword[0])
        f.write("    CONST CW_WALL = $%04X\n" % word("wall"))
        f.write("    CONST CW_TROPHY = $%04X\n" % word("trophy"))
        f.write("    CONST CW_HALF = $%04X\n" % (0x800 | gcard["halfL"] << 3 | BLACK))
        f.write("    CONST CW_DUDHALF = $%04X\n" % (0x800 | gcard["halfL"] << 3 | DUD_FG))
        f.write("    CONST CW_LOGO_TOP = $%04X\n" % (0x800 | fgbg(BLACK, LOGO_TOP)))
        f.write("    CONST CW_LOGO_BOTTOM = $%04X\n" % (0x800 | fgbg(BLACK, LOGO_BOTTOM)))
        f.write("    CONST BG_MASK = $3600\n")
        f.write("    CONST VISOR_COL = $%04X\n" % mobcol(VISOR))
        for i, n in enumerate(FR_NAMES):
            f.write("    CONST FR_%s = %d\n" % (n, i))
        f.write("\n' each arena tile's BACKTAB address\ntpos:\n")
        for i in range(0, len(tpos), ARENA_W):
            f.write("    DATA %s\n" % ", ".join("$%03X" % x for x in tpos[i:i + ARENA_W]))
        f.write("' each tile's card word (proto.h's T_*)\ntword:\n    DATA %s\n" %
                ", ".join("$%04X" % w for w in tword))
        f.write("' the seats' colours, as a MOB's\nseat_col:\n    DATA %s\n" %
                ", ".join("$%04X" % mobcol(c) for c in SEAT_BODY))
        f.write("' and as the HUD's text (black on the seat's colour)\nseat_hud:\n    DATA %s\n" %
                ", ".join("$%04X" % fgbg(BLACK, c) for c in SEAT_BODY))
        # frames: the body's card word (GRAM), its Y flags (DOUBLEY, FLIPX), the visor's card word (0 none),
        # its rows down
        f.write("' each frame (FR_*): the body's card, its Y flags, the visor's card (0: none), its offset\n")
        f.write("fr_body:\n    DATA %s\n" % ", ".join(
            "$%04X" % (0x800 | BODIES.index(b) * 2 << 3) for b, _, _, _ in FRAMES))
        f.write("fr_flags:\n    DATA %s\n" % ", ".join("$%04X" % (0x80 | (0x400 if fl else 0)) for _, fl, _, _ in FRAMES))
        f.write("fr_visor:\n    DATA %s\n" % ", ".join(
            "$%04X" % (0x800 | vcard[v] << 3) if v else "0" for _, _, v, _ in FRAMES))
        f.write("fr_vdy:\n    DATA %s\n" % ", ".join(str(d) for _, _, _, d in FRAMES))

        f.write("\n' GRAM: the bombers (cards 0-%d)\n" % (2 * nb + len(VISORS) - 1))
        cards = []
        for k in BODIES:
            cards += [body[k][0], body[k][1]]
        cards += [visor[k] for k in VISORS]
        data(f, "gram_spr", cards)
        f.write("\n' GRAM: the arena (cards %d-%d), the animated at their first page\n" %
                (G_TILE0, G_TILE0 + len(order) - 1))
        data(f, "gram_arena", [tile(n, 0) for n in order])
        f.write("\n' the animated cards' 4 pages (%d cards each)\n" % len(ANIM))
        data(f, "gram_anim", [tile(n, p) for p in range(4) for n in ANIM])
        f.write("\n' GRAM: the title's logo (cards %d on): a letter's 4 cards, top left, top right,\n"
                "' bottom left, bottom right; its pixels are the background\n" % G_TILE0)
        lc = []
        for i in range(len(LOGO_TEXT)):
            for cy in range(2):
                for cx in range(2):
                    lc.append(card_rows(logo, i * 16 + cx * 8, cy * 8, lambda p: p == PAL[BLACK]))
        data(f, "gram_logo", lc)


if __name__ == "__main__":
    main()
