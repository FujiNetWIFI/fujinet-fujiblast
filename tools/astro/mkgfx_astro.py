#!/usr/bin/env python3
"""mkgfx_astro.py -- gfx/astrocade (tools/astro/drawart_astro.py) as the
Astrocade build's tables: the draw page's tiles and bombers (art.inc), the
title's logo (logo.inc), their equates (artequ.inc).

    mkgfx_astro.py GFXDIR art.inc artequ.inc logo.inc icon.inc

Pure Python (tools/png.py), so the build needs no Pillow.

Tiles: 2 bits a pixel, 2 bytes x 7 lines, two frames each (a still tile's
twice), TILEART + (code*2 + frame) * 14, and TILEPTR, their addresses.

Bombers, in the arena (art.inc): pre-shifted 0-3 pixels, three bytes a row
of 2-bit roles (11 body, 01 visor), ROLEART + (FRMAP[frame]*4 + shift) *
21 + row * 3; MASKT and BODYT turn a role byte into its mask and its
body's pixels (the visor's: the rest of the mask), which the seat's
patterns colour (p_draw.inc).
On the icons' page (icon.inc): two 1-bit masks a row, BOMBART + frame * 14
+ row * 2 = body, visor, and the tiles again (ITILEART, ITILEPTR).
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from png import Image  # noqa: E402
from artlayout import TILES, SPRITES  # noqa: E402

ROLE = {(40, 40, 40): 0, (64, 136, 48): 1, (200, 104, 40): 2, (240, 240, 240): 3}
NCODES = 18                         # T_FLOOR .. T_GLOVE (src/proto.h), then the trophy


def pix(img, x, y):
    return img.px[y][x]


def tiles(img):
    """name -> [frame0 rows, frame1 rows] of role indexes."""
    out = {}
    for i, name in enumerate(TILES):
        fr = []
        for f in range(2):
            rows = [[ROLE[pix(img, f * 8 + x, i * 7 + y)[:3]] for x in range(8)] for y in range(7)]
            fr.append(rows)
        if all(v == 1 for r in fr[1] for v in r) and name != "floor":
            fr[1] = fr[0]               # one frame: shown twice
        out[name] = fr
    return out


def tbytes(rows):
    b = []
    for r in rows:
        for half in range(2):
            v = 0
            for x in range(4):
                v = (v << 2) | r[half * 4 + x]
            b.append(v)
    return b


def db(vals, per=14):
    return ["        DB      " + ",".join("0%02XH" % v for v in vals[i:i + per])
            for i in range(0, len(vals), per)]


def main():
    gfx, art, equ, logo, icon = sys.argv[1:6]
    t = tiles(Image(os.path.join(gfx, "tiles.png")))
    hdr = "; GENERATED by tools/astro/mkgfx_astro.py from gfx/astrocade -- do not edit."
    a = [hdr, "", "; the tiles: (code*2 + frame) * 14, 2 bytes a line, 7 lines", "TILEART:"]
    for name in TILES:
        for f in range(2):
            a += db(tbytes(t[name][f]))
    a += ["", "; TILEPTR: each (code, frame)'s address", "TILEPTR:"]
    n = len(TILES) * 2
    a += ["        DW      " + ",".join("TILEART+%d" % (k * 14) for k in range(i, min(i + 6, n)))
          for i in range(0, n, 6)]
    spr = Image(os.path.join(gfx, "sprites.png"))
    if spr.width != 8 * len(SPRITES) or spr.height != 7:
        sys.exit("mkgfx_astro: sprites.png is not %d frames of 8x7" % len(SPRITES))

    def roles(f):
        """frame f's rows as 8 roles: 3 body, 1 visor, 0 nothing"""
        out = []
        for y in range(7):
            r = []
            for x in range(8):
                p = pix(spr, f * 8 + x, y)
                r.append(0 if p[3] < 128 else 3 if p[:3] == (255, 255, 255) else 1)
            out.append(r)
        return out

    # the arena's bombers: each frame it draws (the knocked-out falls' first
    # two are a walk's), pre-shifted 0-3 pixels into 3 bytes of roles
    arena = [SPRITES.index(n) for n in SPRITES if not n.startswith("win")
             and n not in ("die0", "die1")]
    frmap = []
    for fname in SPRITES:
        alias = {"die0": "up0", "die1": "left0", "win0": "down0", "win1": "down0"}.get(fname, fname)
        frmap.append(arena.index(SPRITES.index(alias)))
    a += ["", "; the arena's frame for each frame (FR_*): its pre-shifted pictures", "FRMAP:"]
    a += db(frmap, 18)
    a += ["", "; the bombers, pre-shifted: (FRMAP[f]*4 + shift) * 21 + row * 3: three",
          "; bytes of 2-bit roles (11 body, 01 visor, 00 nothing)", "ROLEART:"]
    for f in arena:
        rows = roles(f)
        for sh in range(4):
            vals = []
            for r in rows:
                px = [0] * sh + r + [0] * (4 - sh)
                for b in range(3):
                    v = 0
                    for k in range(4):
                        v = (v << 2) | px[b * 4 + k]
                    vals.append(v)
            a += db(vals, 21)

    def table(name, keep):
        out = [name + ":"]
        vals = []
        for v in range(256):
            o = 0
            for k in range(4):
                p = (v >> (6 - 2 * k)) & 3
                if keep(p):
                    o |= 3 << (6 - 2 * k)
            vals.append(o)
        return out + db(vals, 16)
    a += ["", "; a role byte's mask, its body's pixels (page-aligned, in a row: INC H",
          "; steps from one to the next; the visor's are the mask's but the body's)",
          "        DS      (100H-($ AND 0FFH)) AND 0FFH"]
    a += table("MASKT", lambda p: p != 0)
    a += table("BODYT", lambda p: p == 3)
    a += ["MASKP   EQU     MASKT/256"]

    # the icons' page: the tiles again, the bombers as two 1-bit masks a row
    ic = [hdr, "", "; the tiles again (the icons' page)", "ITILEART:"]
    for name in TILES:
        for f in range(2):
            ic += db(tbytes(t[name][f]))
    ic += ["ITILEPTR:"]
    ic += ["        DW      " + ",".join("ITILEART+%d" % (k * 14) for k in range(i, min(i + 6, n)))
           for i in range(0, n, 6)]
    ic += ["", "; the bombers: frame * 14 + row * 2: body, visor (bit 7 the leftmost)", "BOMBART:"]
    for f in range(len(SPRITES)):
        vals = []
        for y in range(7):
            body = visor = 0
            for x in range(8):
                p = pix(spr, f * 8 + x, y)
                if p[3] < 128:
                    continue
                if p[:3] == (255, 255, 255):
                    body |= 0x80 >> x
                else:
                    visor |= 0x80 >> x
            vals += [body, visor]
        ic += db(vals, 14)
    open(icon, "w").write("\n".join(ic) + "\n")
    open(art, "w").write("\n".join(a) + "\n")

    e = [hdr]
    for i, name in enumerate(SPRITES):
        e.append("FR_%-8s EQU %d" % (name.upper(), i))
    e.append("T_TROPHY  EQU %d" % NCODES)
    open(equ, "w").write("\n".join(e) + "\n")

    lg = Image(os.path.join(gfx, "logo.png"))
    if lg.width % 4:
        sys.exit("mkgfx_astro: logo.png is not a whole number of bytes wide")
    # the logo goes on a text screen's ground (colour 0), its shadow colour 1
    lrole = {0: 1, 1: 0, 2: 2, 3: 3}
    rows = [[lrole[ROLE[pix(lg, x, y)[:3]]] for x in range(lg.width)] for y in range(lg.height)]
    L = [hdr, "LOGOW   EQU     %d" % (lg.width // 4), "LOGOH   EQU     %d" % lg.height, "LOGO:"]
    for r in rows:
        vals = []
        for x in range(0, len(r), 4):
            v = 0
            for k in range(4):
                v = (v << 2) | r[x + k]
            vals.append(v)
        L += db(vals, 27)
    open(logo, "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
