#!/usr/bin/env python3
"""mkcanned.py -- src/test.c's canned state (the offline scenes' arena) as
247 bytes for the Arcadia's test page (tools/o2/mkcanned.py's, in 2650 AS
syntax).

    mkcanned.py src/proto.h OUT.inc
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "o2"))
from mkcanned import canned, proto  # noqa: E402


def main(src, out):
    st = canned(proto(src))
    lines = ["; GENERATED by tools/arc/mkcanned.py from src/test.c's canned() -- do not edit.",
             "CANNED:"]
    for i in range(0, len(st), 16):
        lines.append("        DB      " + ",".join("$%02X" % b for b in st[i:i + 16]))
    open(out, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(*sys.argv[1:3])
