#!/usr/bin/env python3
"""mksnd_arc.py -- FujiBlast's effects and jingles for the Arcadia 2001's one
voice (tone, noise, or both; 8 levels): the build's sound tables.

    mksnd_arc.py OUT.inc

The notes are the Adam's (src/adam/sound.c, itself the Atari's): a
frequency, frames, an attenuation (0 loud .. 15 off). Here a note is a
pitch p (the tone is 7867 / (p + 1) Hz; noise is clocked by the same
counter: a smaller p hisses higher), its frames and the VOLUME byte (b3
tone, b4 noise, b0-2 the level, 7 loudest). The jingles are an octave down:
the divider is coarse up high (C6 would be 7% off, an octave down 0.1%).

OUT.inc: SNDIDX, each sound's first note (by SND_*/MUS_* number), then the
notes as three tables, SNDNP (pitch), SNDNF (frames: 0 ends the sound) and
SNDNV (VOLUME).
"""
import sys

TONE, NOISE = 0x08, 0x10


def adam(d):
    return 111861.0 / d             # the Adam's divisor, as Hz


G4, A4, B4, C5, D5, E5, G5, A5, C6 = 392, 440, 494, 523, 587, 659, 784, 880, 1047


def nt(f, l):                       # a note, and its fall (the Adam's NT)
    return [(f / 2, l - 3, 2), (f / 2, 3, 8)]


def rs(l):
    return [(0, l, 15)]


def tone(hz, frames, att):
    return (hz, frames, att, TONE)


def noise(p, frames, att):
    return (-p, frames, att, NOISE)  # a negative "frequency": the pitch itself


FX = {
    "SND_DROP":   [tone(adam(300), 2, 2), tone(adam(220), 2, 4), tone(adam(160), 3, 6)],
    "SND_BOOM":   [noise(40, 3, 0), noise(40, 3, 2), noise(44, 4, 4), noise(48, 4, 6),
                   noise(52, 5, 8), noise(56, 6, 10), noise(60, 6, 12), noise(64, 8, 14)],
    "SND_PICKUP": [tone(G4, 3, 2), tone(B4, 3, 2), tone(D5, 3, 2), tone(G5, 5, 2)],
    "SND_KICK":   [tone(adam(600), 2, 2), tone(adam(420), 2, 4)],
    "SND_THROW":  [tone(adam(140), 2, 4), tone(adam(180), 2, 3), tone(adam(240), 2, 3),
                   tone(adam(360), 3, 4)],
    "SND_FIZZLE": [noise(6, 6, 4), noise(6, 8, 7), noise(6, 10, 10), noise(6, 10, 13)],
    "SND_DIE":    [tone(adam(190), 4, 2), tone(adam(230), 4, 2), tone(adam(270), 4, 3),
                   tone(adam(330), 5, 4), tone(adam(400), 6, 4), tone(adam(470), 6, 5),
                   tone(adam(560), 8, 6), tone(adam(700), 10, 8)],
    "SND_BEEP":   [tone(A4, 6, 3)],
    "SND_GO":     [tone(A5, 16, 2)],
    "SND_SELECT": [tone(C5, 2, 4)],
}


def jingle(parts):
    out = []
    for f, l, a in parts:
        out.append((f, l, a, TONE) if f else (0, l, 15, 0))
    return out


MUS = {
    "MUS_TITLE": jingle(nt(G4, 8) + nt(C5, 8) + nt(E5, 8) + nt(G5, 16) + nt(E5, 8) + nt(G5, 24)
                        + rs(8) + nt(A5, 8) + nt(G5, 8) + nt(E5, 8) + nt(C6, 32)),
    "MUS_ROUND": jingle(nt(C5, 6) + nt(C5, 6) + nt(G5, 18)),
    "MUS_WIN":   jingle(nt(E5, 8) + nt(G5, 8) + nt(C6, 24) + rs(4) + nt(G5, 8) + nt(C6, 32)),
    "MUS_GAME":  jingle(nt(C5, 8) + nt(E5, 8) + nt(G5, 8) + nt(C6, 16) + nt(A5, 8) + nt(C6, 16)
                        + nt(G5, 8) + nt(E5, 8) + nt(G5, 8) + nt(C6, 40)),
}

ORDER = ["SND_DROP", "SND_BOOM", "SND_PICKUP", "SND_KICK", "SND_THROW", "SND_FIZZLE",
         "SND_DIE", "SND_BEEP", "SND_GO", "SND_SELECT",
         "MUS_TITLE", "MUS_ROUND", "MUS_WIN", "MUS_GAME"]


def note(f, frames, att, kind):
    if f < 0:
        p = -f
    elif f == 0:
        p = 0
    else:
        p = max(1, min(127, round(7867.0 / f) - 1))
    level = 0 if att >= 15 else max(1, 7 - att // 2)
    v = (kind | level) if p and level else 0
    return p, frames, v


def main(out):
    idx, notes = [], []
    for name in ORDER:
        idx.append(len(notes))
        for n in (FX.get(name) or MUS[name]):
            notes.append(note(*n))
        notes.append((0, 0, 0))     # the end
    if len(notes) > 255:
        sys.exit("mksnd_arc: %d notes: more than an index reaches" % len(notes))
    lines = ["; GENERATED by tools/arc/mksnd_arc.py -- do not edit.",
             "SNDIDX: DB      " + ",".join(str(i) for i in idx)]
    for label, k in (("SNDNP", 0), ("SNDNF", 1), ("SNDNV", 2)):
        lines.append(label + ":")
        for i in range(0, len(notes), 16):
            lines.append("        DB      " + ",".join("$%02X" % n[k] for n in notes[i:i + 16]))
    open(out, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
