#!/usr/bin/env python3
"""mkgfx_arc.py -- gfx/arcadia/*.png (tools/arc/drawart_arc.py) to the
Arcadia build's tables.

    mkgfx_arc.py GFXDIR OUT.inc EQU.inc LOGO.inc

OUT.inc (the art page's, at ARTBASE): the bombers' 8x8 frames, 8 bytes
each, top row first, bit 7 the left pixel; the user glyphs; the title's
block-graphics cells are LOGO.inc's (the title's page): LOGO, 16 a row
(bits 2-0 the top three blocks left to right, 5-3 the bottom; the ink is
the code's).
EQU.inc (every assembly's: fixed code borrows the art page): A_FRAMES,
A_<GLYPH> their addresses; FR_<NAME> the frame numbers, LOGON the
logo's rows.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, ".."))
from artnames import SPRITES, GLYPH_ORDER  # noqa: E402
from png import Image  # noqa: E402


def bits(img):
    """The image as rows of '#'/'.' (opaque, not black, is lit)."""
    out = []
    for y in range(img.height):
        r = ""
        for x in range(img.width):
            p = img.getpixel((x, y))
            lit = (len(p) < 4 or p[3] > 127) and sum(p[:3]) > 0
            r += "#" if lit else "."
        out.append(r)
    return out


def cellbytes(rows, x0):
    b = []
    for r in rows:
        v = 0
        for k in range(8):
            if r[x0 + k] == "#":
                v |= 0x80 >> k
        b.append(v)
    return b


ARTBASE = 0x0810                    # the art page's data (after its entry table)


def main():
    gfx, out, equ, logo = sys.argv[1:5]
    addr = ARTBASE
    lines = ["; GENERATED by tools/arc/mkgfx_arc.py from gfx/arcadia -- do not edit."]
    eq = ["; GENERATED by tools/arc/mkgfx_arc.py from gfx/arcadia -- do not edit."]
    spr = bits(Image(os.path.join(gfx, "sprites.png")))
    if len(spr) != 8 or len(spr[0]) != 8 * len(SPRITES):
        sys.exit("mkgfx_arc: sprites.png is not %d frames of 8x8" % len(SPRITES))
    lines.append("        ORG     $%04X" % ARTBASE)
    eq.append("A_FRAMES EQU     $%04X" % addr)
    if (addr & 0xFF) + 8 * len(SPRITES) > 0x100:
        sys.exit("mkgfx_arc: the frames cross a 256-byte boundary (VBSYNC adds to the low byte)")
    addr += 8 * len(SPRITES)
    for i, n in enumerate(SPRITES):
        lines.append("        DB      " + ",".join("$%02X" % v for v in cellbytes(spr, 8 * i))
                     + "     ; " + n)
        eq.append("FR_%-8s EQU     %d" % (n.upper(), i))
    gl = bits(Image(os.path.join(gfx, "glyphs.png")))
    if len(gl) != 8 or len(gl[0]) != 8 * len(GLYPH_ORDER):
        sys.exit("mkgfx_arc: glyphs.png is not %d glyphs of 8x8" % len(GLYPH_ORDER))
    for i, n in enumerate(GLYPH_ORDER):
        eq.append("A_%-7s EQU     $%04X" % (n.upper(), addr))
        lines.append("        DB      " + ",".join("$%02X" % v for v in cellbytes(gl, 8 * i))
                     + "     ; " + n)
        addr += 8
    b0 = ARTBASE + 8 * len(SPRITES) + 8 * GLYPH_ORDER.index("bomb0")
    if (b0 & 0xFF) + 48 > 0x100 or GLYPH_ORDER[GLYPH_ORDER.index("bomb0"):][:6] != [
            "bomb0", "bomb1", "flameh0", "flameh1", "flamev0", "flamev1"]:
        sys.exit("mkgfx_arc: the animated glyphs must be bomb0..flamev1 in a row, in one 256")
    lg = bits(Image(os.path.join(gfx, "logo.png")))
    if len(lg) % 2 or len(lg[0]) != 48:
        sys.exit("mkgfx_arc: logo.png is not 48 blocks by an even number of rows")
    lo = ["; GENERATED by tools/arc/mkgfx_arc.py from gfx/arcadia -- do not edit.", "LOGO:"]
    for r in range(0, len(lg), 2):
        cells = []
        for c in range(16):
            v = 0
            for k in range(3):
                if lg[r][3 * c + k] == "#":
                    v |= 4 >> k
                if lg[r + 1][3 * c + k] == "#":
                    v |= 0x20 >> k
            cells.append(v)
        lo.append("        DB      " + ",".join("$%02X" % v for v in cells))
    eq.append("LOGON    EQU     %d" % (len(lg) // 2))
    open(logo, "w").write("\n".join(lo) + "\n")
    open(out, "w").write("\n".join(lines) + "\n")
    open(equ, "w").write("\n".join(eq) + "\n")


if __name__ == "__main__":
    main()
