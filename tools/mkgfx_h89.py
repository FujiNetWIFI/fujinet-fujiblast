#!/usr/bin/env python3
"""mkgfx_h89.py -- gfx/h89/art.txt into gen/h89 (gfxdata.c, gfxcodes.h).

  mkgfx_h89.py OUTDIR                 the build's files
  mkgfx_h89.py --preview PNG [ROM]    the art drawn with the H19's own font
                                      (ROM: its 444-29 character ROM; needs
                                      Pillow, the build doesn't)

A cell is the byte the H19 is sent in graphics mode, bit 7 reverse video;
in sprites 0 is see-through and 01h the seat's digit (src/h89/gfx.c puts
it in). The art's format is described at the top of art.txt.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ART = os.path.join(HERE, "..", "gfx", "h89", "art.txt")

TILES = ["T_FLOOR", "T_PILLAR", "T_BLOCK", "T_BURN", "T_BOMB", "T_DUD",
         "T_FLAME_C", "T_FLAME_H", "T_FLAME_V", "T_FLAME_L", "T_FLAME_R",
         "T_FLAME_U", "T_FLAME_D", "T_FIRE", "T_BOMBUP", "T_SPEED", "T_KICK", "T_GLOVE"]
FRAMES = ["FR_DOWN0", "FR_DOWN1", "FR_DOWN2", "FR_UP0", "FR_UP1", "FR_UP2",
          "FR_RIGHT0", "FR_RIGHT1", "FR_RIGHT2", "FR_LEFT0", "FR_LEFT1", "FR_LEFT2",
          "FR_WIN0", "FR_WIN1", "FR_DIE0", "FR_DIE1", "FR_DIE2", "FR_DIE3"]
SEAT = 0x01
REV = 0x80


def parse(path):
    items, name, kind = {}, None, None
    for n, raw in enumerate(open(path), 1):
        line = raw.rstrip("\n")
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if line.startswith("["):
            words = line.strip("[] ").split()
            name, kind = words[0], (words[1] if len(words) > 1 else "cells")
            items[name] = (kind, [])
            continue
        if name is None:
            sys.exit(f"{path}:{n}: art before any [NAME]")
        if kind == "bitmap":
            items[name][1].append(line.strip())
            continue
        if not line.startswith("|") or line.count("|") < 2:
            sys.exit(f"{path}:{n}: a cell row is |chars| mask")
        end = line.index("|", 1)
        chars, mask = line[1:end], line[end + 1:].strip()
        if not mask:
            mask = "." * len(chars)
        if len(mask) != len(chars):
            sys.exit(f"{path}:{n}: the mask is {len(mask)} letters for {len(chars)} cells")
        row = []
        for c, m in zip(chars, mask):
            if m == "T":
                row.append(0)
                continue
            if c == "@":
                v = SEAT
            else:
                v = ord(c)
                if not 0x20 <= v <= 0x7E:
                    sys.exit(f"{path}:{n}: {c!r} isn't a byte the H19 shows")
            if m == "R":
                v |= REV
            elif m != ".":
                sys.exit(f"{path}:{n}: mask letter {m!r} (. R T)")
            row.append(v)
        items[name][1].append(row)
    return items


def cells(items, name, w, h):
    kind, rows = items.get(name, (None, None))
    if kind != "cells":
        sys.exit(f"art.txt: no [{name}]")
    if len(rows) != h or any(len(r) != w for r in rows):
        sys.exit(f"art.txt: [{name}] must be {w} x {h}")
    return [v for r in rows for v in r]


def bitmap(items, name):
    """Half blocks: two pixel rows a cell row."""
    kind, rows = items.get(name, (None, None))
    if kind != "bitmap":
        sys.exit(f"art.txt: no [{name} bitmap]")
    w = max(len(r) for r in rows)
    rows = [r.ljust(w, ".") for r in rows]
    if len(rows) % 2:
        rows.append("." * w)
    out = []
    for y in range(0, len(rows), 2):
        for x in range(w):
            top, bot = rows[y][x] == "X", rows[y + 1][x] == "X"
            out.append({(0, 0): 0x20, (1, 0): ord("p"), (0, 1): ord("p") | REV,
                        (1, 1): 0x20 | REV}[(top, bot)])
    return out, w, len(rows) // 2


def table(name, vals, per=16):
    s = f"const uint8_t {name}[{len(vals)}] = {{\n"
    for i in range(0, len(vals), per):
        s += "    " + ", ".join("0x%02X" % v for v in vals[i:i + per]) + ",\n"
    return s + "};\n"


def build(out):
    items = parse(ART)
    tiles = [v for t in TILES for v in cells(items, t, 5, 2)]
    frames = [v for f in FRAMES for v in cells(items, f, 3, 2)]
    logo, lw, lh = bitmap(items, "LOGO")
    tro, tw, th = bitmap(items, "TROPHY")
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "gfxcodes.h"), "w") as f:
        f.write("/* GENERATED by tools/mkgfx_h89.py from gfx/h89/art.txt: do not edit. */\n")
        f.write("#ifndef GFXCODES_H\n#define GFXCODES_H\n#include <stdint.h>\n\n")
        for i, n in enumerate(FRAMES):
            f.write(f"#define {n:<11} {i}\n")
        f.write(f"\n#define N_FRAMES    {len(FRAMES)}\n")
        f.write(f"#define TILE_W      5\n#define TILE_H      2\n#define FIG_W       3\n#define FIG_H       2\n")
        f.write(f"#define LOGO_W      {lw}\n#define LOGO_H      {lh}\n")
        f.write(f"#define TROPHY_W    {tw}\n#define TROPHY_H    {th}\n#define SEAT_CELL   0x{SEAT:02X}\n\n")
        f.write("extern const uint8_t tile_art[];      /* N_TILES x TILE_W x TILE_H */\n")
        f.write("extern const uint8_t frame_art[];     /* N_FRAMES x FIG_W x FIG_H */\n")
        f.write("extern const uint8_t logo_art[];\nextern const uint8_t trophy_art[];\n\n#endif\n")
    with open(os.path.join(out, "gfxdata.c"), "w") as f:
        f.write("/* GENERATED by tools/mkgfx_h89.py from gfx/h89/art.txt: do not edit. */\n")
        f.write("#include <stdint.h>\n\n")
        f.write(table("tile_art", tiles, 10))
        f.write(table("frame_art", frames, 6))
        f.write(table("logo_art", logo, lw))
        f.write(table("trophy_art", tro, tw))


def preview(png, rom_path):
    from PIL import Image
    rom = open(rom_path, "rb").read()
    items = parse(ART)

    def glyph(v):
        code = v & 0x7F
        g = rom[(code & 0x1F) * 16:(code & 0x1F) * 16 + 10] if code >= 0x5E else \
            rom[code * 16:code * 16 + 10]
        return [[bool(b & (0x80 >> i)) ^ bool(v & REV) for i in range(8)] for b in g]

    # one picture: the tiles in a row, the frames for seat 1 (and reversed:
    # our own), the logo, the trophy; cells 8 x 20 (lines doubled, as the
    # desktop shows the H19)
    rows = []
    rows.append([v for t in TILES for v in cells(items, t, 5, 2)[:5] + [0x20]])
    rows.append([v for t in TILES for v in cells(items, t, 5, 2)[5:] + [0x20]])
    rows.append([0x20] * 108)
    for rev in (0, REV):
        top, bot = [], []
        for fr in FRAMES:
            c = [(ord("1") if v == SEAT else v) ^ (rev if v else 0) for v in cells(items, fr, 3, 2)]
            top += [x or 0x20 for x in c[:3]] + [0x20]
            bot += [x or 0x20 for x in c[3:]] + [0x20]
        rows += [top, bot, [0x20] * 72]
    logo, lw, lh = bitmap(items, "LOGO")
    for y in range(lh):
        rows.append(logo[y * lw:(y + 1) * lw])
    rows.append([0x20])
    tro, tw, th = bitmap(items, "TROPHY")
    for y in range(th):
        rows.append((tro[y * tw:(y + 1) * tw] + [0x20]) * 5)
    w = max(len(r) for r in rows)
    img = Image.new("RGB", (w * 8 + 16, len(rows) * 20 + 16), (0, 0, 0))
    px = img.load()
    for ry, r in enumerate(rows):
        for rx, v in enumerate(r):
            for gy, gl in enumerate(glyph(v)):
                for gx, on in enumerate(gl):
                    if on:
                        for d in (0, 1):
                            px[8 + rx * 8 + gx, 8 + ry * 20 + gy * 2 + d] = (255, 255, 255)
    img.save(png)


if __name__ == "__main__":
    if len(sys.argv) >= 3 and sys.argv[1] == "--preview":
        preview(sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else
                os.path.expanduser("~/.local/share/fujinet-go-h89/roms/2716_444-29_h19font.u420"))
    elif len(sys.argv) == 2:
        build(sys.argv[1])
    else:
        sys.exit(__doc__)
