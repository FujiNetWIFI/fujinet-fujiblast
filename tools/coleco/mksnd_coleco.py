#!/usr/bin/env python3
"""mksnd_coleco.py SOUND_C OUT.inc -- the Adam port's tunes (src/adam/sound.c)
as zmac data: per tune, notes of 4 bytes (divisor lo, hi, frames, attenuation)
ending in a note of 0 frames. Divisor bit 15 is the noise channel (the low
bits its control), 0 a rest. The C file's macros are evaluated here, so the
two stay one source.
"""
import re
import sys


def main():
    src = open(sys.argv[1]).read()
    env = {}
    HZ = lambda f: 111861 // f
    NOISE = lambda c: 0x8000 | c
    NT = lambda n, l: [(n, l - 3, 2), (n, 3, 8)]
    RS = lambda l: [(0, l, 15)]
    env.update(HZ=HZ, NOISE=NOISE, NT=NT, RS=RS, END=(0, 0, 0))
    for name, expr in re.findall(r"#define\s+([A-G]\d)\s+(HZ\(\d+\))", src):
        env[name] = eval(expr, env)

    def tune(body):
        body = body.replace("{", "(").replace("}", ")")
        items = eval("[" + body + "]", env)
        notes = []
        for it in items:
            notes.extend(it if isinstance(it, list) else [it])
        return notes

    tunes = {}
    for name, body in re.findall(r"static const Note (\w+)\[\]\s*=\s*\{(.*?)\};", src, re.S):
        tunes[name] = tune(body)
    fx = re.search(r"fx\[SND_COUNT\]\s*=\s*\{(.*?)\};", src, re.S).group(1).split(",")
    mus = re.search(r"mus\[MUS_COUNT\]\s*=\s*\{(.*?)\};", src, re.S).group(1).split(",")
    fx = [x.strip() for x in fx if x.strip()]
    mus = [x.strip() for x in mus if x.strip()]
    out = ["; GENERATED by tools/coleco/mksnd_coleco.py from src/adam/sound.c -- do not edit.",
           "; effects 0-%d, then the jingles: the table of each tune's address, then the tunes" % (len(fx) - 1)]
    out.append("SNDTAB:")
    for n in fx + mus:
        out.append("        DW      T_%s" % n.upper())
    for n in fx + mus:
        out.append("T_%s:" % n.upper())
        for d, f, a in tunes[n]:
            out.append("        DW      %d" % d)
            out.append("        DB      %d,%d" % (f, a))
    open(sys.argv[2], "w").write("\n".join(out) + "\n")
    print("mksnd_coleco: %d effects, %d jingles, %d bytes" % (len(fx), len(mus),
          sum(4 * len(tunes[n]) for n in fx + mus) + 2 * len(fx + mus)))


if __name__ == "__main__":
    main()
