#!/usr/bin/env python3
"""mkgfx_coleco.py OUTDIR -- the Adam port's art tables (tools/mkgfx_tms.py's
gen/adam/gfxdata.c, gfxcodes.h) as zmac includes.

    python3 tools/coleco/mkgfx_coleco.py OUTDIR     # art.inc, artequ.inc

Run tools/mkgfx_tms.py gen/adam first (make gen-adam does).
artequ.inc holds the equates (the codes, the counts); art.inc the tables,
each under a label of its own, flat, in the C arrays' order.
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
GEN = os.path.join(ROOT, "gen", "adam")
ARRAYS = ["arena_cells", "anim_cells", "tile_chars", "tile_anim_kind", "logo_cells", "logo_map",
          "trophy_cells", "spr_a", "spr_b", "spr_bigA", "spr_bigB", "font_gfx"]


def main():
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    c = open(os.path.join(GEN, "gfxdata.c")).read()
    h = open(os.path.join(GEN, "gfxcodes.h")).read()
    equ = ["; GENERATED by tools/coleco/mkgfx_coleco.py -- do not edit."]
    for name, val in re.findall(r"#define\s+([A-Z0-9_]+)\s+(\d+)\s*$", h, re.M):
        equ.append("%-12s EQU     %s" % (name, val))
    open(os.path.join(out, "artequ.inc"), "w").write("\n".join(equ) + "\n")
    # art.inc: what every screen needs (the fixed region); art0.inc: the rest
    # split: artl.inc the logo and trophy (fixed, 8000H), art0.inc the sprite patterns (made once: page 0)
    parts = {"art.inc": ["arena_cells", "anim_cells", "tile_chars", "tile_anim_kind", "font_gfx"],
             "artl.inc": ["logo_cells", "logo_map", "trophy_cells"],
             "art0.inc": ["spr_a", "spr_b", "spr_bigA", "spr_bigB"]}
    for fname, names in parts.items():
        emit(c, out, fname, names)


def emit(c, out, fname, names):
    lines = ["; GENERATED by tools/coleco/mkgfx_coleco.py -- do not edit."]
    for name in names:
        m = re.search(r"const uint8_t %s\b[^=]*=\s*\{(.*?)\};" % name, c, re.S)
        body = m.group(1)
        nums = [int(x, 16) if x.lower().startswith("0x") else int(x) for x in re.findall(r"0x[0-9A-Fa-f]+|\d+", body)]
        lines.append("A_%s:" % name.upper())
        for i in range(0, len(nums), 16):
            lines.append("        DB      " + ",".join("%d" % n for n in nums[i:i + 16]))
        lines.append("; %s: %d bytes" % (name, len(nums)))
    open(os.path.join(out, fname), "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
