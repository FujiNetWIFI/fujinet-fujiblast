#!/usr/bin/env python3
"""mkmus_nes.py -- FujiBlast's in-play music (music/play.txt, tools/mus.py)
for the NES's APU (src/nes/snd.s): ch1 on the triangle (the bass, and the
kick as a falling thump) and the noise channel (snare, hat); ch2 on pulse 2.
The Atari's converter (tools/mkmus_atari.py) is the model: each channel of a
pattern is a subroutine (the same data once), each channel's order a list of
calls.

Steps of A, B, jiffies as snd.s plays them (jiffies 1-252):

    lo   hi   $FE       call (one level)
    0    0    $FD       return
    lo   hi   $FF       jump

ch1 (A, B):   B = 0                silent
              B = $40 | hi         triangle, A the timer's low byte
              B = $80 | volume     noise: A is $400E (mode, period)
ch2 (A, B):   B low nibble = 0     silent
              B = hi << 4 | volume pulse 2, A the timer's low byte

The triangle has no volume, so the bass has no envelope. Its timer: f =
1789773 / (32 (t + 1)); pulse: 1789773 / (16 (t + 1)).

usage: mkmus_nes.py music/play.txt OUTDIR [OCTAVES]   (writes OUTDIR/music.s;
OCTAVES shifts the bass: a triangle at E1 is faint on a TV's speaker)"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mus  # noqa: E402

CPU = 1789773.0
ACLOCK = 63921.0            # the Atari's, whose steps the sweeps copy
CALL, RET, JUMP = 0xFE, 0xFD, 0xFF
MAXN = 252

# $400E of the drums: mode << 7 | period index (4 8 16 32 64 96 128 160 ...)
NOISE = {"S": 0x06, "H": 0x83}


def cents(f, want):
    return 1200 * math.log2(f / want)


def tri_t(hz):
    return max(2, min(2047, round(CPU / (32 * hz)) - 1))


def pul_t(hz):
    return max(8, min(2047, round(CPU / (16 * hz)) - 1))


def vol(k, steps):
    """the volume k jiffies in: steps is ((until, volume), ...)"""
    for until, v in steps:
        if k < until:
            return v
    return steps[-1][1]


def tri(hz):
    t = tri_t(hz)
    return (t & 255, 0x40 | t >> 8)


def pulse(hz, v):
    if v == 0:
        return (0, 0)
    t = pul_t(hz)
    return (t & 255, (t >> 8) << 4 | v)


def ch1(ev, octaves):
    """(A, B) for one jiffy of ch1"""
    if ev is None:
        return (0, 0)
    kind, note, k = ev
    if kind == "K":                     # a falling thump
        return tri((150.0, 70.0)[k])
    if kind == "S":
        return (NOISE["S"], 0x80 | (0xC, 0x6, 0x6)[k])
    if kind == "H":
        return (NOISE["H"], 0x80 | 6)
    if kind == "bass":
        return tri(mus.hz(note) * 2 ** octaves)
    raise SystemExit("no ch1 voice for %r" % kind)


def ch2(ev):
    """(A, B) for one jiffy of ch2"""
    if ev is None:
        return (0, 0)
    kind, note, k = ev
    hz = mus.hz(note)
    if kind == "blip":
        return pulse(hz, vol(k, ((2, 6), (4, 3), (999, 0))))
    if kind == "tone":
        return pulse(hz, vol(k, ((2, 6), (999, 4))))
    if kind in ("arp", "arpmaj", "warble"):
        return pulse(hz, 5)
    k &= ~1                             # slides: a step every other jiffy
    if kind == "sweep":                 # down, fading (the Atari's divisor x 1.08 a step)
        return pulse(max(125.0, hz / 1.08 ** k), max(1, 6 - k // 4))
    if kind == "rise":
        return pulse(min(ACLOCK / 18, hz / 0.96 ** k), vol(k, ((24, 5), (999, 6))))
    raise SystemExit("no pulse voice for %r" % kind)


def steps(evs, ch, octaves):
    """jiffy by jiffy -> steps (A, B, n)"""
    out = []
    for fc in (ch1(e, octaves) if ch == 0 else ch2(e) for e in evs):
        if out and tuple(out[-1][:2]) == fc and out[-1][2] < MAXN:
            out[-1][2] += 1
        else:
            out.append([fc[0], fc[1], 1])
    return out


def main():
    src, outdir = sys.argv[1], sys.argv[2]
    octaves = int(sys.argv[3]) if len(sys.argv) > 3 else 0
    song = mus.parse(src)
    subs = [{}, {}]                     # per channel: steps -> label
    order = [[], []]
    for name in song.order:
        lens = set()
        for ch in (0, 1):
            evs = mus.frames(song, name, ch + 1)
            lens.add(len(evs))
            key = tuple(map(tuple, steps(evs, ch, octaves)))
            if key not in subs[ch]:
                subs[ch][key] = "m%d_%d" % (ch + 1, len(subs[ch]))
            order[ch].append(subs[ch][key])
        if len(lens) != 1:
            raise SystemExit("%s: pattern %s's channels differ in length" % (src, name))

    lines = ["; GENERATED by tools/mkmus_nes.py from %s: edit that, not this." % src,
             "; Steps A, B, jiffies; $FE call, $FD return, $FF jump (src/nes/snd.s).",
             "; NO_MUSIC (a build with no room for it) leaves it out.",
             "        .ifndef NO_MUSIC",
             "        .export _m_loop1, _m_loop2", "",
             '        .segment "MUSIC"']
    size = 0
    for ch in (0, 1):
        top = "_m_loop%d" % (ch + 1)
        lines.append(top + ":")
        for lab in order[ch]:
            lines.append("        .byte   <%s, >%s, $%02X" % (lab, lab, CALL))
        tgt = "%s + %d" % (top, 3 * song.loop)
        lines.append("        .byte   <(%s), >(%s), $%02X" % (tgt, tgt, JUMP))
        size += 3 * (len(order[ch]) + 1)
        for key, lab in subs[ch].items():
            lines.append(lab + ":")
            for a, b, n in key:
                lines.append("        .byte   $%02X, $%02X, %d" % (a, b, n))
            lines.append("        .byte   0, 0, $%02X" % RET)
            size += 3 * (len(key) + 1)
    lines.append("        .endif")
    os.makedirs(outdir, exist_ok=True)
    with open(os.path.join(outdir, "music.s"), "w") as f:
        f.write("\n".join(lines) + "\n")

    jiffies = sum(len(song.patterns[n]) for n in song.order) * song.tempo
    print("music: %d bars, %.1f s a loop at 60 Hz, %d bytes, %d+%d subroutines, bass %+d octave"
          % (len(song.order), jiffies / 60, size, len(subs[0]), len(subs[1]), octaves))
    used = sorted({ev[1] for n in song.order for ev in mus.frames(song, n, 1)
                   if ev and ev[0] == "bass"})
    names = "C C# D Eb E F F# G G# A Bb B".split()
    out = []
    for n in used:
        want = mus.hz(n) * 2 ** octaves
        t = tri_t(want)
        out.append("%s%d t=%d %+.1fc" % (names[n % 12], n // 12 - 1 + octaves, t,
                                         cents(CPU / (32 * (t + 1)), want)))
    print("bass (triangle): " + ", ".join(out))


if __name__ == "__main__":
    main()
