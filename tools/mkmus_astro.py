#!/usr/bin/env python3
"""mkmus_astro.py -- FujiBlast's in-play music (music/play.txt, tools/mus.py)
for the Astrocade's custom I/O chip (src/astrocade/src/p_snd.inc): ch1's bass
and kick on tone B, its snare and hat on the noise N, ch2 (the robots'
chatter) on tone C. Tone A stays free for the effects.

The lists are p_snd.inc's own: steps of T (the tone period; 0 a rest), volume,
frames, decay, ended by four zeros. A bar is one list a channel, so the player
(MUSFEED) can start any channel anywhere in the bar by walking the steps: the
music keeps time under an effect and comes back mid-bar when it ends.

MUSORD, a bar a record of 7 bytes: its length in jiffies, the lists of B, C, N
(the channels' order in SNDCH, which MUSFEED steps through).

Tone: f = 1789773 / (2 (MO+1) (T+1)); the bass is shifted up OCTAVES (default
2, as the SMS's: E1 is 41 Hz, and 165 Hz after).

usage: mkmus_astro.py music/play.txt OUT.inc [OCTAVES]"""
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "astro"))
import mus  # noqa: E402
import mksnd_astro as snd  # noqa: E402

BASS_VOL = 10
# the NES's chatter volume 0-6 as the Astrocade's 0-15
CHAT = {0: 0, 1: 3, 2: 5, 3: 6, 4: 7, 5: 8, 6: 9}
SNARE = (10, 8, 6)              # a volume a jiffy
HAT = 5


def period(hz):
    t = round(snd.CLOCK / (2 * (snd.MO + 1) * hz)) - 1
    if not 1 <= t <= 255:
        raise SystemExit("mkmus_astro: %.1f Hz is outside the tone's range (T=%d)" % (hz, t))
    return t


def cents(t, want):
    return 1200 * math.log2(snd.CLOCK / (2 * (snd.MO + 1) * (t + 1)) / want)


def vol(k, steps):
    for until, v in steps:
        if k < until:
            return v
    return steps[-1][1]


def chat(hz, v):
    return (0, 0) if v == 0 else (period(hz), CHAT[v])


def ch_b(ev, octaves):
    if ev is None or ev[0] in ("S", "H"):
        return (0, 0)
    kind, note, k = ev
    if kind == "K":                     # a falling thump
        return (period((220.0, 140.0)[k]), BASS_VOL)
    return (period(mus.hz(note) * 2 ** octaves), BASS_VOL)


def ch_n(ev):
    if ev is None or ev[0] not in ("S", "H"):
        return (0, 0)
    kind, _, k = ev
    return (0, SNARE[k] if kind == "S" else HAT)


def ch_c(ev):
    if ev is None:
        return (0, 0)
    kind, note, k = ev
    hz = mus.hz(note)
    if kind == "blip":
        return chat(hz, vol(k, ((2, 6), (4, 3), (999, 0))))
    if kind == "tone":
        return chat(hz, vol(k, ((2, 6), (999, 4))))
    if kind in ("arp", "arpmaj", "warble"):
        return chat(hz, 5)
    k &= ~1                             # slides: a step every other jiffy
    if kind == "sweep":
        return chat(max(140.0, hz / 1.08 ** k), max(1, 6 - k // 4))
    if kind == "rise":
        return chat(min(3500.0, hz / 0.96 ** k), vol(k, ((24, 5), (999, 6))))
    raise SystemExit("no chatter voice for %r" % kind)


def steps(pairs):
    out = []
    for fc in pairs:
        if fc[1] == 0:
            fc = (0, 0)
        if out and tuple(out[-1][:2]) == fc and out[-1][2] < 250:
            out[-1][2] += 1
        else:
            out.append([fc[0], fc[1], 1, 0])
    return out


def main():
    src, out = sys.argv[1], sys.argv[2]
    octaves = int(sys.argv[3]) if len(sys.argv) > 3 else 2
    song = mus.parse(src)
    lists = {}                          # steps -> label
    bars = []
    for name in song.order:
        e1, e2 = mus.frames(song, name, 1), mus.frames(song, name, 2)
        if len(e1) != len(e2) or len(e1) > 255:
            raise SystemExit("%s: bar %s is %d/%d jiffies" % (src, name, len(e1), len(e2)))
        recs = []
        for key in (steps(ch_b(e, octaves) for e in e1),
                    steps(ch_c(e) for e in e2),
                    steps(ch_n(e) for e in e1)):
            key = tuple(map(tuple, key))
            if key not in lists:
                lists[key] = "MUL%d" % len(lists)
            recs.append(lists[key])
        bars.append((len(e1), recs))

    lines = ["; GENERATED by tools/mkmus_astro.py from %s: edit that, not this." % src,
             "; MUSORD: a bar a record: jiffies, the lists of B, C, N (p_snd.inc).",
             "MUSNB   EQU     %d" % len(bars),
             "MUSLP   EQU     %d" % song.loop,
             "MUSORD:"]
    for n, recs in bars:
        lines.append("        DB      %d" % n)
        lines.append("        DW      %s" % ",".join(recs))
    lines.append("MUSBEG:")
    size = 7 * len(bars)
    for key, lab in lists.items():
        flat = []
        for st in key:
            flat += list(st)
        flat += [0, 0, 0, 0]
        size += len(flat)
        lines.append(lab + ":")
        for i in range(0, len(flat), 16):
            lines.append("        DB      " + ",".join("%d" % v for v in flat[i:i + 16]))
    lines.append("MUSEND:")
    open(out, "w").write("\n".join(lines) + "\n")

    jiffies = sum(n for n, _ in bars)
    print("music: %d bars, %.1f s a loop at 60 Hz, %d bytes, %d lists, bass %+d octaves"
          % (len(bars), jiffies / 60, size, len(lists), octaves))
    used = sorted({ev[1] for n in song.order for ev in mus.frames(song, n, 1)
                   if ev and ev[0] == "bass"})
    names = "C C# D Eb E F F# G G# A Bb B".split()
    res = []
    for n in used:
        want = mus.hz(n) * 2 ** octaves
        t = period(want)
        res.append("%s%d T=%d %+.1fc" % (names[n % 12], n // 12 - 1 + octaves, t, cents(t, want)))
    print("bass (tone B): " + ", ".join(res))


if __name__ == "__main__":
    main()
