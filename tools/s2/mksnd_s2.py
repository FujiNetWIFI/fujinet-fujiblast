#!/usr/bin/env python3
"""mksnd_s2.py -- FujiBlast's sounds for the Studio II's one fixed tone:
every cue a rhythm of (jiffies on, jiffies off) pairs, 0 at the end
(src/studio2/src/sound.inc plays them).

    mksnd_s2.py src/apple2/sndtab.s OUT.inc

The jingles keep their melodies' rhythm (src/apple2/sndtab.s: each note N
f, l rings l - 2 and leaves a 2-jiffy gap so repeated notes stay apart; a
rest R l lengthens the gap before the next). The effects are drawn here by
hand to the Atari's shapes: a blast rumbles, a fall slows, a pick-up climbs.
A gap under 2 jiffies is not heard (the ISR's beep runs on into the next).
"""
import re
import sys

EFFECTS = {
    "drop":   [(2, 0)],
    "boom":   [(3, 2), (3, 2), (4, 2), (6, 0)],
    "pickup": [(3, 2), (3, 2), (3, 2), (5, 0)],
    "kick":   [(2, 2), (2, 0)],
    "throw":  [(2, 2), (2, 2), (2, 2), (3, 0)],
    "fizzle": [(1, 2), (1, 3), (1, 4), (1, 0)],
    "die":    [(4, 2), (4, 2), (4, 2), (5, 2), (6, 2), (6, 2), (8, 2), (10, 0)],
    "beep":   [(6, 0)],
    "go":     [(16, 0)],
    "select": [(2, 0)],
}
ORDER = ["drop", "boom", "pickup", "kick", "throw", "fizzle", "die", "beep", "go", "select",
         "title", "round", "win", "game"]


def jingles(path):
    out, cur = {}, None
    for line in open(path):
        line = line.split(";")[0].rstrip()
        m = re.match(r"_m_(\w+):\s*(.*)", line)
        if m:
            cur = m.group(1)
            out[cur] = []
            line = "        " + m.group(2)
        if cur is None:
            continue
        m = re.match(r"\s+N\s+\w+,\s*(\d+)", line)
        if m:
            n = int(m.group(1))
            out[cur].append([max(1, n - 2), 2])
            continue
        m = re.match(r"\s+R\s+(\d+)", line)
        if m and out[cur]:
            out[cur][-1][1] += int(m.group(1))
            continue
        if re.match(r"\s+END", line):
            out[cur][-1][1] = 0
            cur = None
    return out


def main(src, dst):
    seq = dict(EFFECTS)
    for k, v in jingles(src).items():
        seq[k] = [tuple(p) for p in v]
    lines = ["; GENERATED by tools/s2/mksnd_s2.py from %s -- do not edit." % src,
             "        PFIT    %d" % (2 * len(ORDER)),
             "SNDTAB: DW      " + ", ".join("sn_" + k for k in ORDER[:7]),
             "        DW      " + ", ".join("sn_" + k for k in ORDER[7:])]
    for k in ORDER:
        b = []
        for on, off in seq[k]:
            b += [on, off]
        lines.append("sn_%s: DB      %s, 0" % (k, ", ".join(str(x) for x in b)))
    open(dst, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(*sys.argv[1:3])
