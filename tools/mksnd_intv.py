#!/usr/bin/env python3
"""mksnd_intv.py -- FujiBlast's sounds for the Intellivision's PSG
(src/intv/sound.bas): the Atari's own, as src/apple2/sndtab.s has them for
the Mockingboard (steps of AUDF, AUDC, jiffies; 0 jiffies ends), into
IntyBASIC DATA. sound.bas turns AUDF into the PSG's period as it plays.

usage: mksnd_intv.py src/apple2/sndtab.s gen/intv/snd.bas"""
import re
import sys

FX = ["drop", "boom", "pickup", "kick", "throw", "fizzle", "die", "beep", "go", "select"]
MUS = ["title", "round", "win", "game"]


def main():
    src, out = sys.argv[1], sys.argv[2]
    consts, sounds, cur = {}, {}, None

    def val(t):
        t = t.strip()
        if t in consts:
            return consts[t]
        return int(t[1:], 16) if t.startswith("$") else int(t)

    for line in open(src):
        line = line.split(";", 1)[0].rstrip()
        m = re.match(r"^(\w+)\s*=\s*(\S+)$", line.strip())
        if m:
            consts[m.group(1)] = val(m.group(2))
            continue
        m = re.match(r"^_([sm]_\w+):\s*(.*)$", line)
        if m:
            cur = m.group(1)
            sounds[cur] = []
            line = m.group(2)
        if cur is None:
            continue
        s = line.strip()
        if not s:
            continue
        op, _, args = s.partition(" ")
        a = [x for x in args.split(",") if x.strip()]
        if op == ".byte":
            sounds[cur] += [val(x) for x in a]
        elif op == "N":
            f, ln = val(a[0]), val(a[1])
            sounds[cur] += [f, 0xA8, ln - 3, f, 0xA4, 3]
        elif op == "R":
            sounds[cur] += [0, 0xA0, val(a[0])]
        elif op == "END":
            sounds[cur] += [0, 0, 0]
            cur = None

    data, offs = [], {}
    for name in ["s_" + n for n in FX] + ["m_" + n for n in MUS]:
        steps = sounds[name]
        assert len(steps) % 3 == 0 and steps[-1] == 0, name
        offs[name] = len(data)
        data += steps
    with open(out, "w") as f:
        f.write("' GENERATED by tools/mksnd_intv.py from src/apple2/sndtab.s: steps of\n"
                "' AUDF, AUDC, jiffies (POKEY's), 0 jiffies ends.\n")
        f.write("snd_fx:\n    DATA %s\n" % ", ".join(str(offs["s_" + n]) for n in FX))
        f.write("snd_mus:\n    DATA %s\n" % ", ".join(str(offs["m_" + n]) for n in MUS))
        f.write("snd_data:\n")
        for i in range(0, len(data), 15):
            f.write("    DATA %s\n" % ", ".join(str(x) for x in data[i:i + 15]))


if __name__ == "__main__":
    main()
