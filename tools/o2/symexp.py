#!/usr/bin/env python3
"""symexp.py -- named symbols from an AS listing's symbol table, as equates.

    symexp.py LISTING OUT.inc NAME...
"""
import re
import sys


def main(lst, out, names):
    syms = {}
    text = open(lst, errors="ignore").read()
    for m in re.finditer(r"\b([A-Za-z_][A-Za-z_0-9]*)\s*:\s+([0-9A-F]+) [A-Z-] ", text):
        syms.setdefault(m.group(1), int(m.group(2), 16))
    lines = ["; GENERATED by tools/o2/symexp.py from %s -- do not edit." % lst.split("/")[-1]]
    for n in names:
        if n not in syms:
            sys.exit("symexp: %s: no symbol %s" % (lst, n))
        lines.append("%-12s equ 0%Xh" % (n, syms[n]))
    open(out, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3:])
