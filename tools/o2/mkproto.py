#!/usr/bin/env python3
"""mkproto.py -- src/proto.h's #defines as Macroassembler AS equates.

    mkproto.py src/proto.h OUT.inc
"""
import re
import sys


def main(src, out):
    lines = ["; GENERATED by tools/o2/mkproto.py from src/proto.h -- do not edit."]
    for line in open(src):
        m = re.match(r"#define\s+([A-Z_][A-Z_0-9]*)\s+(\d+)\s*$", line)
        if m:
            lines.append("%-14s equ %s" % m.groups())
    open(out, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(*sys.argv[1:3])
