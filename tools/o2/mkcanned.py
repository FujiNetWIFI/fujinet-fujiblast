#!/usr/bin/env python3
"""mkcanned.py -- src/test.c's canned state (the offline scenes' arena) as
247 bytes for the Odyssey 2's test page: gen/o2/canned.inc.

    mkcanned.py src/proto.h OUT.inc
"""
import re
import sys


def proto(path):
    d = {}
    for line in open(path):
        m = re.match(r"#define\s+([A-Z_][A-Z_0-9]*)\s+(\d+)\s*$", line)
        if m:
            d[m.group(1)] = int(m.group(2))
    return d


def canned(p):
    st = bytearray(p["STATE_SIZE"])
    W, H = p["ARENA_W"], p["ARENA_H"]

    def PL(s, f):
        return p["OFF_PLAYERS"] + s * p["PLAYER_SIZE"] + f

    def MAPT(t):
        return p["OFF_MAP"] + t

    st[p["OFF_PHASE"]] = p["PH_PLAY"]
    st[p["OFF_ROUND"]] = 2
    st[p["OFF_ROUNDS"]] = 5
    st[p["OFF_TIMER"]] = 154
    st[p["OFF_SEATED"]] = 0x0F
    st[p["OFF_INPLAY"]] = 0x0F
    st[p["OFF_ALIVE"]] = 0x07
    st[p["OFF_CONN"]] = 0x0F
    st[p["OFF_HOST"]] = 0
    st[p["OFF_RESULT"]] = 2
    st[p["OFF_SEQ"]] = 1
    names = [b"ANN", b"BOB", b"CAT", b"DOT"]
    corner = [(0, 0), (p["MAX_X"], p["MAX_Y"]), (p["MAX_X"], 0), (0, p["MAX_Y"])]
    for s in range(4):
        o = p["OFF_NAMES"] + s * p["NAME_LEN"]
        st[o:o + len(names[s])] = names[s]
        st[PL(s, p["P_X"])], st[PL(s, p["P_Y"])] = corner[s]
        st[PL(s, p["P_DIR"])] = p["DIR_DOWN"]
        st[PL(s, p["P_RANGE"])] = 2
        st[PL(s, p["P_BOMBS"])] = 1
        st[PL(s, p["P_WINS"])] = s
    t = 0
    for r in range(H):
        for c in range(W):
            if c & 1 and r & 1:
                st[MAPT(t)] = p["T_PILLAR"]
            elif 2 < c < 10 and (r in (0, 10) or c in (4, 8)):
                st[MAPT(t)] = p["T_BLOCK"]
            t += 1
    put = {(2, 0): "T_BOMB", (4, 0): "T_DUD", (2, 12): "T_FIRE", (4, 12): "T_BOMBUP",
           (6, 12): "T_SPEED", (8, 12): "T_KICK", (6, 0): "T_GLOVE", (8, 0): "T_BURN",
           (5, 6): "T_FLAME_C", (5, 5): "T_FLAME_H", (5, 4): "T_BLOCK", (5, 7): "T_FLAME_H",
           (5, 8): "T_FLAME_R", (4, 6): "T_FLAME_V", (3, 6): "T_FLAME_U", (6, 6): "T_FLAME_D"}
    for (r, c), k in put.items():
        st[MAPT(r * W + c)] = p[k]
    st[p["OFF_MOVERS"]] = p["M_SLIDE"]
    st[p["OFF_MOVERS"] + 1] = 2 * p["UNIT"] + 8
    st[p["OFF_MOVERS"] + 2] = 2 * p["UNIT"]
    return st


def main(src, out):
    st = canned(proto(src))
    lines = ["; GENERATED by tools/o2/mkcanned.py from src/test.c's canned() -- do not edit.",
             "canned_st:"]
    for i in range(0, len(st), 16):
        lines.append("    db " + ", ".join("%03Xh" % b for b in st[i:i + 16]))
    open(out, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(*sys.argv[1:3])
