#!/usr/bin/env python3
"""mkgfx_o2.py -- the Odyssey 2's bombers: sprite shapes.

    mkgfx_o2.py OUT.inc FRAMES.inc [PREVIEW.png]

OUT.inc holds the shapes (`frames:`, read by MOVP: include it beside its
reader); FRAMES.inc the FR_* numbers, for every page.

A bomber is one of the 8244's four sprites (8 x 8, each row 2 lines), in its
seat's colour. The frames are the 8244 font's own man -- standing and walking
right, walking and standing left, facing forward (glyphs 50-53, 58) -- as the
user chose (2026-11-11), plus frames of our own: forward mirrored (walking up
and down, cheering) and knocked out. A glyph is 7 rows with bit 7 leftmost; a
sprite row has bit 0 leftmost, so every row is reversed, and the figure sits
in rows 1-7 (its feet on the tile's bottom line).

Frame numbers (FR_* in the output) are the order of FRAMES below.
"""
import sys

# The 8244 font's man (charset rows, bit 7 = leftmost pixel).
MAN_R = [0x1C, 0x1C, 0x18, 0x1E, 0x18, 0x18, 0x1C]
MAN_RW = [0x1C, 0x1C, 0x18, 0x1E, 0x18, 0x34, 0x26]
MAN_LW = [0x38, 0x38, 0x18, 0x78, 0x18, 0x2C, 0x64]
MAN_L = [0x38, 0x38, 0x18, 0x78, 0x18, 0x18, 0x38]
MAN_F = [0x38, 0x38, 0x12, 0xFE, 0xB8, 0x28, 0x6C]


def mirror(rows):
    return [int("{:08b}".format(r)[::-1], 2) for r in rows]


def art(*lines):
    return [int(l.replace(".", "0").replace("#", "1"), 2) for l in lines]


# Ours: knocked out -- staggering, folding, flat.
DIE0 = art("..#.#...",
           "...#....",
           "..###...",
           "..###...",
           ".#.#.#..",
           "...#....",
           "..#.#...")
DIE1 = art("........",
           "........",
           "........",
           "..###...",
           ".#####..",
           "#.###.#.",
           ".#...#..")
DIE2 = art("........",
           "........",
           "........",
           "........",
           "........",
           "##......",
           "########")

FRAMES = [
    ("RIGHT0", MAN_R), ("RIGHT1", MAN_RW),
    ("LEFT0", MAN_L), ("LEFT1", MAN_LW),
    ("FWD0", MAN_F), ("FWD1", mirror(MAN_F)),
    ("DIE0", DIE0), ("DIE1", DIE1), ("DIE2", DIE2),
]


def sprite(rows):
    """7 glyph rows -> 8 sprite rows, bit 0 leftmost, figure in rows 1-7."""
    return [0] + [int("{:08b}".format(r)[::-1], 2) for r in rows]


def main(out, frout, preview=None):
    eq = ["; GENERATED by tools/o2/mkgfx_o2.py -- do not edit.",
          "; the bombers' sprite frames (mkgfx_o2.py FRAMES)"]
    for k, (name, _) in enumerate(FRAMES):
        eq.append("FR_%-7s equ %d" % (name, k))
    eq.append("NFRAMES    equ %d" % len(FRAMES))
    open(frout, "w").write("\n".join(eq) + "\n")
    lines = ["; GENERATED by tools/o2/mkgfx_o2.py -- do not edit.",
             "; the bombers' sprite frames, 8 bytes each (bit 0 leftmost)",
             "frames:"]
    for name, rows in FRAMES:
        lines.append("    db " + ", ".join("%03Xh" % b for b in sprite(rows)) + "   ; " + name)
    open(out, "w").write("\n".join(lines) + "\n")
    if preview:
        from PIL import Image
        sc = 8
        im = Image.new("RGB", (len(FRAMES) * 10 * sc, 18 * sc), (0, 80, 0))
        px = im.load()
        for k, (_, rows) in enumerate(FRAMES):
            for y, b in enumerate(sprite(rows)):
                for x in range(8):
                    if b >> x & 1:
                        for dy in range(2 * sc):
                            for dx in range(sc):
                                px[(k * 10 + 1 + x) * sc + dx, (1 + 2 * y) * sc + dy] = (255, 255, 255)
        im.save(preview)


if __name__ == "__main__":
    main(*sys.argv[1:4])
