#!/usr/bin/env python3
"""mkovdata.py -- the overlays' bytes for the swap page (src/o2/src/ov.inc):
each overlay's $600-$6F7 and $700-$7F3 in a 256-byte page of its own, with a
copy stub at the page's $F8 (MOVP reads only the page the code is in).

    mkovdata.py OUT.inc BASE NAME=FILE...   (BASE: the first page, e.g. 900)

FILE is a 512-byte image of $600-$7FF.
"""
import sys

N6, N7 = 0xF8, 0xF4


def main(out, base, specs):
    at = int(base, 16)
    lines = ["; GENERATED by tools/o2/mkovdata.py -- do not edit."]
    for spec in specs:
        name, path = spec.split("=", 1)
        img = open(path, "rb").read()
        if len(img) != 512:
            sys.exit("mkovdata: %s is %d bytes" % (path, len(img)))
        for half, part, n in (("6", img[:N6], N6), ("7", img[256:256 + N7], N7)):
            lab = "%s%s" % (name, half)
            lines.append("    org 0%Xh" % at)
            lines.append("%s:" % lab)
            for i in range(0, n, 16):
                lines.append("    db " + ", ".join("%03Xh" % b for b in part[i:i + 16]))
            lines.append("    org 0%Xh" % (at + 0xF8))
            lines.append("%s_c:                        ; r6 bytes from offset r4 to POKE (r0 at REGDATA)" % lab)
            lines += ["    mov a,r4", "    movp a,@a", "    movx @r0,a", "    inc r4",
                      "    djnz r6,%s_c" % lab, "    ret"]
            at += 0x100
    open(out, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3:])
