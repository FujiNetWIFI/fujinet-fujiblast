#!/usr/bin/env python3
"""mknet.py OUTDIR -- the decoder's offset table: build/a26/netdata.inc.

SDEST[off] for st offsets 0-87 is 0 (drop), a zero-page cell (>= $80: the byte
is stored there) or a small special code (< $80) the decoder handles itself.
The names are in terms of fbdefs.inc's symbols, so the table cannot drift.
"""
import os
import sys

SP_TIMER = 1
SP_WINS = 2      # 2-5
SP_WARP = 6      # 6-9
SP_X = 16        # 16-19
SP_Y = 20        # 20-23
SP_DIR = 24      # 24-27
SP_NAME = 30
SP_ALIVE = 28
SP_MINE = 32      # 32-47: flags 32+p, bombs 36+p, speed 40+p, out 44+p (my seat only)


def main():
    out = sys.argv[1]
    d = ["0"] * 88
    d[0] = "PHASE"
    d[2] = "ROUNDS"
    d[3] = "HOST"
    d[4] = str(SP_TIMER)
    d[5] = "RESULT"
    d[6] = "SEATED"
    d[7] = str(SP_ALIVE)
    for p in range(4):
        b = 16 + 10 * p
        d[b + 0] = str(SP_X + p)
        d[b + 1] = str(SP_Y + p)
        d[b + 2] = str(SP_DIR + p)
        d[b + 3] = str(SP_MINE + p)
        d[b + 5] = str(SP_MINE + 4 + p)
        d[b + 6] = str(SP_MINE + 8 + p)
        d[b + 7] = str(SP_MINE + 12 + p)
        d[b + 8] = str(SP_WINS + p)
        d[b + 9] = str(SP_WARP + p)
    for i in range(32):
        d[56 + i] = str(SP_NAME)
    L = ["; GENERATED by tools/a26/mknet.py -- do not edit.", "SDEST:"]
    for i in range(0, 88, 8):
        L.append("        db      " + ",".join(d[i:i + 8]))
    L += ["SP_TIMER EQU %d" % SP_TIMER, "SP_WINS EQU %d" % SP_WINS, "SP_WARP EQU %d" % SP_WARP,
          "SP_X EQU %d" % SP_X, "SP_Y EQU %d" % SP_Y, "SP_DIR EQU %d" % SP_DIR, "SP_NAME EQU %d" % SP_NAME, "SP_ALIVE EQU %d" % SP_ALIVE, "SP_MINE EQU %d" % SP_MINE]
    offs = [(r >> 1) * 128 + 83 + 13 * (r & 1) for r in range(11)]
    L.append("MROFFL:")
    L.append("        db      " + ",".join(str(o & 255) for o in offs))
    L.append("MROFFH:")
    L.append("        db      " + ",".join(str(o >> 8) for o in offs))
    L.append("BITS8:  db      1,2,4,8,16,32,64,128,1,2,4")
    open(os.path.join(out, "netdata.inc"), "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
