#!/usr/bin/env python3
"""mkarena.py -- the Atari 2600 client's generated arena includes.

    mkarena.py OUTDIR

OUTDIR/rows.inc    the unrolled kernel pairs (from mkspike.pair_code)
OUTDIR/art.inc     the compose bank's tables: ART, KCLASS, CBTAB, the per-
                   register tile lists and their contribution tables
OUTDIR/canned.inc  the canned map (143 bytes, row major) for the test boot

The art is mkspike.py's LOOK 1 (picked 2026-11-12): pillars and blocks share a
colour; a row holding a flame, bomb or power-up draws its static kinds on the
even entries and the dynamic kinds on the odd ones.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mkspike as sp  # noqa: E402

NK = 18
STRIDE = 7


def kclass(k):
    if k in (sp.PILLAR, sp.BLOCK):
        return 1
    if k in sp.POWER:
        return 2
    if k in sp.BOMBS:
        return 3
    if k in sp.FLAMES:
        return 4
    return 0


def art_table():
    """ART[set*126 + kind*7 + p] -> 3 bits.  set 0: quiet row; set 1: busy row."""
    t = bytearray(2 * NK * STRIDE)
    for s in (0, 1):
        for k in range(NK):
            a = sp.ART_FULL.get(k)
            for p in range(STRIDE):
                v = 0
                if a is not None:
                    v = a[p]
                    if s == 1:
                        if k in sp.STATIC:
                            v = v if p % 2 == 0 else 0
                        else:
                            v = v if p % 2 == 1 else 0
                t[s * NK * STRIDE + k * STRIDE + p] = v
    return t


def reg_lists():
    """For each register 0-5: the tiles it overlaps and, per tile, the 8
    contribution bytes (indexed by the tile's 3 art bits)."""
    heads, counts, cols, ct = [], [], [], bytearray()
    for r in range(6):
        half, kind = divmod(r, 3)
        base = 20 * half + (0, 4, 12)[kind]
        ln = (4, 8, 8)[kind]
        c0, c1 = base // 3, (base + ln - 1) // 3
        heads.append(len(cols))
        counts.append(min(c1, sp.W - 1) - c0 + 1)
        for c in range(c0, min(c1, sp.W - 1) + 1):
            cols.append(c)
            for v in range(8):
                m = 0
                for k in range(3):
                    px = 3 * c + k
                    if base <= px < base + ln and v & (4 >> k):
                        i = px - base
                        m |= (1 << (4 + i)) if kind == 0 else ((1 << (7 - i)) if kind == 1 else (1 << i))
                ct.append(m)
    return heads, counts, cols, ct


def db(name, data, width=16):
    out = ["%s:" % name]
    for i in range(0, len(data), width):
        out.append("        db      " + ",".join("$%02X" % v for v in data[i:i + width]))
    return out


def main():
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    open(os.path.join(out, "rows.inc"), "w").write(sp.kernel_asm())

    heads, counts, cols, ct = reg_lists()
    assert len(cols) <= 31
    L = ["; GENERATED by tools/a26/mkarena.py -- do not edit.",
         "NLIST   EQU     %d" % len(cols)]
    L += db("KCLASS", bytes(kclass(k) for k in range(NK)) + bytes(14))
    L += db("CBTAB", bytes([sp.C_STATIC, sp.C_STATIC, sp.C_POWER, sp.C_BOMB, sp.C_FLAME]))
    L += db("K7", bytes(k * 7 for k in range(NK)))
    L += db("MROWL", bytes((0x1800 + (r >> 1) * 128 + 83 + 13 * (r & 1)) & 255 for r in range(11)))
    L += db("MROWH", bytes((0x1800 + (r >> 1) * 128 + 83 + 13 * (r & 1)) >> 8 for r in range(11)))
    L += db("RHEAD", bytes(heads))
    L += db("RCOUNT", bytes(counts))
    L += db("LCOL", bytes(cols))
    L.append("        ALIGN   256")
    L += db("ART", art_table())
    L.append("        ALIGN   256")
    L += db("CTAB", ct)
    open(os.path.join(out, "art.inc"), "w").write("\n".join(L) + "\n")

    # arena bank tables: world y -> entry, entry -> row / offset
    yent = bytes((y >> 4) * 7 + (((y & 15) * 7) >> 4) for y in range(161))
    L = ["; GENERATED by tools/a26/mkarena.py -- do not edit."]
    L += db("YENT", yent)
    L += db("E2ROW", bytes(min(e // 7, 10) for e in range(84)))
    L += db("E2MOD", bytes(e % 7 for e in range(84)))
    open(os.path.join(out, "ptab.inc"), "w").write("\n".join(L) + "\n")

    L = ["; GENERATED by tools/a26/mkarena.py -- do not edit."]
    L += db("MROWL", bytes((0x1800 + (r >> 1) * 128 + 83 + 13 * (r & 1)) & 255 for r in range(11)))
    L += db("MROWH", bytes((0x1800 + (r >> 1) * 128 + 83 + 13 * (r & 1)) >> 8 for r in range(11)))
    open(os.path.join(out, "maprows.inc"), "w").write("\n".join(L) + "\n")

    L = ["; GENERATED by tools/a26/mkarena.py -- do not edit.",
         "; one tile's seven entries into the register's accumulators, unrolled"]
    for e in range(7):
        L += ["        ldy     #%d" % e, "        lda     (CARTP),y", "        tay",
              "        lda     (CTP),y", "        ora     RACC+%d" % e, "        sta     RACC+%d" % e]
    open(os.path.join(out, "jloop.inc"), "w").write("\n".join(L) + "\n")

    m = sp.canned()
    flat = bytes(v for row in m for v in row)
    L = ["; GENERATED by tools/a26/mkarena.py -- do not edit."]
    offs = [(r >> 1) * 128 + 83 + 13 * (r & 1) for r in range(11)]
    L += db("MROFFL", bytes(o & 255 for o in offs))
    L += db("MROFFH", bytes(o >> 8 for o in offs))
    L += db("CANMAP", flat, 13)
    open(os.path.join(out, "canned.inc"), "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
