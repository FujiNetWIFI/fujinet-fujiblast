#!/usr/bin/env python3
"""mkscr.py OUTDIR -- the text screens: build/a26/scr.inc.

Each screen is 21 rows: a colour byte per row (bit 7 set: a seat row, the low
two bits the seat; else an NTSC colour) and the strings the rows start with.
Dynamic cells (names, wins, timers, values) are blitted over them later.
"""
import os
import sys

WHITE, GOLD, GREY, RED, CYAN, GREEN = 0x0E, 0x1E, 0x08, 0x36, 0x9E, 0xCC

SCREENS = {}


def screen(name, rows):
    SCREENS[name] = rows


def seatrows():
    r = {}
    for s in range(4):
        r[5 + 2 * s] = (0x80 | s, "%d" % (s + 1))
    return r


base = {0: (WHITE, "FUJIBLAST")}
w = dict(base)
w.update(seatrows())
w.update({2: (GREY, "WAITING ROOM"), 14: (GREY, "ROUNDS"), 17: (WHITE, "HOST: FIRE"),
          18: (WHITE, "STARTS"), 19: (GREY, "LEFT/RIGHT"), 20: (GREY, "SETS ROUNDS")})
screen("WAIT", w)
r = dict(base)
r.update(seatrows())
r.update({2: (GOLD, "ROUND OVER"), 14: (GREY, "NEXT ROUND"), 15: (GREY, "IN")})
screen("ROUND", r)
o = dict(base)
o.update(seatrows())
o.update({2: (GOLD, "GAME OVER"), 14: (GREY, "BACK TO ROOM"), 15: (GREY, "IN")})
screen("OVER", o)
screen("CONN", {0: (WHITE, "FUJIBLAST"), 8: (GREY, "CONNECTING"), 10: (GREY, "TO THE")
                , 11: (GREY, "SERVER")})
screen("LOST", {0: (WHITE, "FUJIBLAST"), 8: (RED, "LINK LOST"), 11: (GREY, "PRESS RESET"),
                12: (GREY, "TO RETRY")})
screen("TITLE", {3: (WHITE, "FUJIBLAST"), 6: (GOLD, "A BOMB MAZE"), 7: (GOLD, "FOR 2-4"),
                 14: (GREY, "FIRE: PLAY"), 17: (GREY, "FUJINET")})

screen("NAME", {0: (WHITE, "FUJIBLAST"), 3: (GOLD, "WHO ARE YOU?"), 12: (GREY, "UP DOWN: ABC"),
                13: (GREY, "FIRE: ADD"), 14: (GREY, "LEFT: DELETE"), 15: (GREY, "RIGHT: DONE")})
screen("ROOMS", {0: (WHITE, "FUJIBLAST"), 1: (GOLD, "PICK A ROOM"), 3: (GREY, ""), 4: (GREY, ""),
                 5: (GREY, ""), 6: (GREY, ""), 7: (GREY, ""), 8: (GREY, ""), 9: (GREY, ""),
                 10: (GREY, ""), 14: (GREY, "UP DOWN: PICK"), 15: (GREY, "FIRE: JOIN")})

ORDER = ["WAIT", "ROUND", "OVER", "CONN", "LOST", "TITLE", "NAME", "ROOMS"]


def main():
    out = sys.argv[1]
    L = ["; GENERATED by tools/a26/mkscr.py -- do not edit."]
    strs = []
    for n in ORDER:
        rows = SCREENS[n]
        L.append("SCC_%s:" % n)
        L.append("        db      " + ",".join("$%02X" % (rows[k][0] if k in rows else GREY) for k in range(21)))
    for n in ORDER:
        rows = SCREENS[n]
        L.append("SCR_%s:" % n)
        for k in range(21):
            if k in rows:
                lab = "S_%s_%d" % (n, k)
                L.append("        db      %d" % k)
                L.append("        dw      %s" % lab)
                strs.append((lab, rows[k][1]))
        L.append("        db      $FF")
    for lab, t in strs:
        L.append('%s: db "%s",0' % (lab, t))
    L.append("SCCL:   db      " + ",".join("<SCC_%s" % n for n in ORDER).replace("<", "(").replace(",", ")&$FF,") + ")&$FF")
    L.append("SCCH:   db      " + ",".join("SCC_%s>>8" % n for n in ORDER))
    L.append("SCRL:   db      " + ",".join("SCR_%s" % n for n in ORDER).replace(",", "&$FF,") + "&$FF")
    L.append("SCRH:   db      " + ",".join("SCR_%s>>8" % n for n in ORDER))
    open(os.path.join(out, "scr.inc"), "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
