#!/usr/bin/env bash
# build.sh -- assemble the Atari 2600 FujiBlast client: build/a26/fujiblst.bin
# (32K: fifteen 2K banks at $1000, then the fixed half).  Env: FUJI_FIRMWARE
# (the fn-2600 tree, default ~/Workspace/fn-2600).
set -euo pipefail
cd "$(dirname "$0")/../.."
FUJI_FIRMWARE="${FUJI_FIRMWARE:-$HOME/Workspace/fn-2600}"
VCS="$FUJI_FIRMWARE/pico/atari-2600"
AS=$HOME/asl/asl P2BIN=$HOME/asl/p2bin
OUT=build/a26${PAL:+-pal}
SRC=src/atari2600
mkdir -p "$OUT"

python3 "$VCS/tools/checkdefs.py" "$VCS/firmware/include/fuji_mailbox.h" "$SRC/fujinet.inc" \
  --extra "FB_TCELL=FN_BLIT_TCELL,FB_PATH=FN_BLIT_PATH,FB_TEXT=FN_BLIT_TEXT,FNBGEN=FN_B_BLITGEN,FH_BSL=FN_HOT_BLIT_SL,FH_BSH=FN_HOT_BLIT_SH,FH_BDL=FN_HOT_BLIT_DL,FH_BDH=FN_HOT_BLIT_DH,FH_BCNT=FN_HOT_BLIT_CNT,FH_BGO=FN_HOT_BLIT_GO,FP_POPCH=FN_PATH_POPCH,FP_SEL0=FN_PATH_SEL0,FP_SEL1=FN_PATH_SEL1,FP_SEL2=FN_PATH_SEL2,FP_SEL3=FN_PATH_SEL3,FP_SEED=FN_PATH_SEED,FP_COMMIT=FN_PATH_COMMIT,FNTROW=FN_T_ROWS,FNTCLH=FN_T_CELL_H,FB_POKE=FN_BLIT_POKE,FB_PPOKE=FN_BLIT_PATHPOKE"

python3 tools/a26/mkarena.py "$OUT"
python3 tools/a26/mknet.py "$OUT"
python3 tools/a26/mkscr.py "$OUT"
python3 tools/a26/mksnd.py "$OUT"
{
    echo "; generated by build.sh -- do not edit"
    printf 'DEFHOST: DB      "%s"\n' "${DEFSRV:-fujinet.online:9910}/"
    echo "        DB      0"
} > "$OUT/endpoint.inc"

assemble() {   # NAME
    ( cd "$SRC" && "$AS" -q -L -i . -i "../../$OUT" ${PAL:+-D PAL=1} "$1.asm" )
    mv "$SRC/$1.p" "$OUT/$1.p"
    mv -f "$SRC/$1.lst" "$OUT/$1.lst"
}

assemble mtail
python3 tools/a26/mktail.py "$OUT/mtail.lst" \
    FNRW,FNARM,FNCHK,FNBEG,FNPB,FNPW,FNLNCH,FNGO,FNACK,FNROWA,FNCHR,FNSPC > "$OUT/tail.inc"
tail -1 "$OUT/tail.inc" | sed 's/^; */  tail: /'

BANKS="boot arena compose net play screens netdec - - - - - - - -"
parts=(); lsts=()
for b in $BANKS; do
    [ "$b" = "-" ] && b=stub
    assemble "$b"
    python3 tools/a26/checkbanks.py "$OUT/$b.lst" $((0x1800)) "$b"
    "$P2BIN" "$OUT/$b.p" "$OUT/$b.bin" -r '$1000-$17FF' -l 0 >/dev/null
    parts+=("$OUT/$b.bin"); lsts+=("$OUT/$b.lst")
done
"$P2BIN" "$OUT/mtail.p" "$OUT/mtail.bin" -r '$1800-$1FFF' -l 0 >/dev/null
cat "${parts[@]}" "$OUT/mtail.bin" > "$OUT/fujiblst.bin"
size=$(stat -c%s "$OUT/fujiblst.bin")
printf 'FUJI' | dd of="$OUT/fujiblst.bin" bs=1 seek=$((size - 0x800 + 0x0710)) conv=notrunc status=none
echo "$OUT/fujiblst.bin: $size bytes"
python3 tools/a26/checkrom.py $(python3 tools/a26/dataranges.py "${lsts[@]}") "$OUT/fujiblst.bin"
