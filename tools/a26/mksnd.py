#!/usr/bin/env python3
"""mksnd.py OUTDIR -- the sound effects: build/a26/snd.inc.

One TIA voice, stepped once a frame (a step = AUDF, AUDC<<4|AUDV). SND is the
step index in play; 0 = silent; an AUDC/AUDV byte of $FF ends an effect.
"""
import os
import sys

FX = {}


def fx(name, steps):
    FX[name] = steps


def sweep(c, f0, f1, v0, v1, n):
    out = []
    for i in range(n):
        f = round(f0 + (f1 - f0) * i / max(n - 1, 1))
        v = round(v0 + (v1 - v0) * i / max(n - 1, 1))
        out.append((f, c, v))
    return out


fx("BEEP", sweep(4, 9, 9, 9, 7, 6))
fx("GO", sweep(4, 5, 3, 10, 8, 12))
fx("DROP", sweep(12, 12, 24, 9, 3, 8))
fx("BOOM", sweep(8, 6, 28, 12, 0, 18))
fx("DIE", sweep(4, 6, 31, 11, 0, 22))
fx("PICK", sweep(12, 14, 4, 8, 8, 10))
win = []
for f in (13, 10, 8, 6):
    win += sweep(4, f, f, 10, 8, 6)
fx("WIN", win)
over = []
for f in (13, 11, 10, 8, 10, 8, 6, 5):
    over += sweep(4, f, f, 10, 7, 5)
fx("OVER", over)


def main():
    out = sys.argv[1]
    f, c = [0], [0xFF]
    L = ["; GENERATED by tools/a26/mksnd.py -- do not edit."]
    E = ["; GENERATED by tools/a26/mksnd.py -- do not edit."]
    for name, steps in FX.items():
        E.append("SND_%s EQU %d" % (name, len(f)))
        for fr, ch, vol in steps:
            f.append(fr)
            c.append((ch << 4) | vol)
        f.append(0)
        c.append(0xFF)
    assert len(f) <= 255, len(f)
    L.append("SNDF:   db      " + ",".join(str(x) for x in f))
    L.append("SNDC:   db      " + ",".join("$%02X" % x for x in c))
    open(os.path.join(out, "snd.inc"), "w").write("\n".join(L) + "\n")
    open(os.path.join(out, "sndequ.inc"), "w").write("\n".join(E) + "\n")


if __name__ == "__main__":
    main()
