#!/usr/bin/env python3
"""mkmus_sms.py -- FujiBlast's in-play music (music/play.txt, tools/mus.py)
for the SMS's SN76489 (src/sms/sound.c, mus_step): ch1 on tone 2 (the bass,
and the kick as a falling thump) and the noise channel (snare, hat); ch2
(the robots' chatter) on tone 0. The NES's converter (tools/mkmus_nes.py) is
the model: each channel of a pattern is a subroutine (the same data once),
each channel's order a list of calls.

Steps of A, B, jiffies as mus_step plays them (jiffies 1-252):

    lo   hi   $FE       call (one level)
    0    0    $FD       return
    lo   hi   $FF       jump

ch1 (A, B):   B = 0                silent
              B = $40 | N >> 4     tone 2, A = N & 15 | attenuation << 4
              B = $80              noise, A = control | attenuation << 4
ch2 (A, B):   B = 0                silent
              B = $40 | N >> 4     tone 0, A = N & 15 | attenuation << 4

Tone: f = 3579545 / (32 N), N 1-1023, so nothing under 109 Hz: the bass is
shifted up OCTAVES (default 2: E1 is 41 Hz, and 165 Hz after). Attenuation 0
is loud, 15 off (2 dB a step).

usage: mkmus_sms.py music/play.txt OUTDIR [OCTAVES] [--zmac]
(writes OUTDIR/music.asm; --zmac: OUTDIR/music.inc for zmac, the ColecoVision's
src/coleco/sound.inc, labels MLOOP1/MLOOP2)"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mus  # noqa: E402

PSG = 3579545.0
ACLOCK = 63921.0            # the Atari's, whose steps the sweeps copy
CALL, RET, JUMP = 0xFE, 0xFD, 0xFF
MAXN = 252

# noise control: bit 2 white, low bits the rate (0: N/512, 1: N/1024, 2: N/2048)
NOISE = {"S": 0x05, "H": 0x04}
# the NES's volume 0-6 as an attenuation (the PSG's steps are logarithmic)
ATT = {0: 15, 1: 12, 2: 10, 3: 9, 4: 8, 5: 7, 6: 6}
BASS_ATT = 2


def cents(f, want):
    return 1200 * math.log2(f / want)


def tone_n(hz):
    n = round(PSG / (32 * hz))
    if n > 1023:
        raise SystemExit("mkmus_sms: %.1f Hz is below the PSG's 109 Hz (raise OCTAVES)" % hz)
    return max(2, n)


def tone(hz, att):
    n = tone_n(hz)
    return ((att << 4) | (n & 15), 0x40 | n >> 4)


def vol(k, steps):
    for until, v in steps:
        if k < until:
            return v
    return steps[-1][1]


def chat(hz, v):
    return (0, 0) if v == 0 else tone(hz, ATT[v])


def ch1(ev, octaves):
    if ev is None:
        return (0, 0)
    kind, note, k = ev
    if kind == "K":                     # a falling thump
        return tone((220.0, 110.0)[k], 2)
    if kind == "S":
        return (NOISE["S"] | (3, 6, 6)[k] << 4, 0x80)
    if kind == "H":
        return (NOISE["H"] | 8 << 4, 0x80)
    if kind == "bass":
        return tone(mus.hz(note) * 2 ** octaves, BASS_ATT)
    raise SystemExit("no ch1 voice for %r" % kind)


def ch2(ev):
    if ev is None:
        return (0, 0)
    kind, note, k = ev
    hz = mus.hz(note)
    if kind == "blip":
        return chat(hz, vol(k, ((2, 6), (4, 3), (999, 0))))
    if kind == "tone":
        return chat(hz, vol(k, ((2, 6), (999, 4))))
    if kind in ("arp", "arpmaj", "warble"):
        return chat(hz, 5)
    k &= ~1                             # slides: a step every other jiffy
    if kind == "sweep":
        return chat(max(125.0, hz / 1.08 ** k), max(1, 6 - k // 4))
    if kind == "rise":
        return chat(min(3500.0, hz / 0.96 ** k), vol(k, ((24, 5), (999, 6))))
    raise SystemExit("no chatter voice for %r" % kind)


def steps(evs, ch, octaves):
    out = []
    for fc in (ch1(e, octaves) if ch == 0 else ch2(e) for e in evs):
        if out and tuple(out[-1][:2]) == fc and out[-1][2] < MAXN:
            out[-1][2] += 1
        else:
            out.append([fc[0], fc[1], 1])
    return out


def main():
    zmac = "--zmac" in sys.argv
    argv = [a for a in sys.argv if a != "--zmac"]
    src, outdir = argv[1], argv[2]
    octaves = int(argv[3]) if len(argv) > 3 else 2
    song = mus.parse(src)
    subs = [{}, {}]
    order = [[], []]
    for name in song.order:
        lens = set()
        for ch in (0, 1):
            evs = mus.frames(song, name, ch + 1)
            lens.add(len(evs))
            key = tuple(map(tuple, steps(evs, ch, octaves)))
            if key not in subs[ch]:
                subs[ch][key] = "m%d_%d" % (ch + 1, len(subs[ch]))
            order[ch].append(subs[ch][key])
        if len(lens) != 1:
            raise SystemExit("%s: pattern %s's channels differ in length" % (src, name))

    if zmac:
        lines = ["; GENERATED by tools/mkmus_sms.py --zmac from %s: edit that, not this." % src,
                 "; Steps A, B, jiffies; $FE call, $FD return, $FF jump (src/coleco/sound.inc)."]
        dw, db, pre, top0 = "DW", "DB", "MU", "MLOOP"
        hexb = lambda v: "0%02XH" % v
    else:
        lines = ["; GENERATED by tools/mkmus_sms.py from %s: edit that, not this." % src,
                 "; Steps A, B, jiffies; $FE call, $FD return, $FF jump (src/sms/sound.c).",
                 "        IFNDEF NO_MUSIC",
                 "        SECTION rodata_user",
                 "        PUBLIC  _m_loop1, _m_loop2"]
        dw, db, pre, top0 = "defw", "defb", "", "_m_loop"
        hexb = lambda v: "$%02X" % v
    size = 0
    for ch in (0, 1):
        top = "%s%d" % (top0, ch + 1)
        lines.append(top + ":")
        for lab in order[ch]:
            lines.append("        %s    %s" % (dw, pre + lab))
            lines.append("        %s    %s" % (db, hexb(CALL)))
        lines.append("        %s    %s + %d" % (dw, top, 3 * song.loop))
        lines.append("        %s    %s" % (db, hexb(JUMP)))
        size += 3 * (len(order[ch]) + 1)
        for key, lab in subs[ch].items():
            lines.append(pre + lab + ":")
            for a, b, n in key:
                lines.append("        %s    %s, %s, %d" % (db, hexb(a), hexb(b), n))
            lines.append("        %s    0, 0, %s" % (db, hexb(RET)))
            size += 3 * (len(key) + 1)
    if not zmac:
        lines.append("        ENDIF")
    os.makedirs(outdir, exist_ok=True)
    with open(os.path.join(outdir, "music.inc" if zmac else "music.asm"), "w") as f:
        f.write("\n".join(lines) + "\n")

    jiffies = sum(len(song.patterns[n]) for n in song.order) * song.tempo
    print("music: %d bars, %.1f s a loop at 60 Hz, %d bytes, %d+%d subroutines, bass %+d octave"
          % (len(song.order), jiffies / 60, size, len(subs[0]), len(subs[1]), octaves))
    used = sorted({ev[1] for n in song.order for ev in mus.frames(song, n, 1)
                   if ev and ev[0] == "bass"})
    names = "C C# D Eb E F F# G G# A Bb B".split()
    out = []
    for n in used:
        want = mus.hz(n) * 2 ** octaves
        t = tone_n(want)
        out.append("%s%d N=%d %+.1fc" % (names[n % 12], n // 12 - 1 + octaves, t,
                                         cents(PSG / (32 * t), want)))
    print("bass (tone 2): " + ", ".join(out))


if __name__ == "__main__":
    main()
