#!/usr/bin/env python3
"""mkgfx_vga.py -- gfx/vga/*.png, tools/vgapal.py and gfx/namco.bin -> the
MS-DOS VGA build's data (src/msdos/vga/gfx.c).

    python3 tools/mkgfx_vga.py OUTDIR    # writes OUTDIR/gfxdata.c, gfxcodes.h

Mode 13h: a byte a pixel, a DAC entry. The art is one far block, gfx_art
(offsets A_*), a line's bytes left to right, lines top to bottom:
  A_TILES   tile frames, 16x16 (the grass already under them)
  A_CELLS   the arena's wall and the side panels' cell, 8x8
  A_ICONS   the five powerups lit, 16x16, 0 where the backdrop shows
  A_TROPHY  16x16, 0 where the backdrop shows
  A_LOGO    LOGO_W x LOGO_H, 0 where the backdrop shows
  A_SPR     bomber frames, 16x16, in codes (0 clear; + SEAT + 16*seat)
  A_BIG     the two cheering frames, 32x32, the same
Near data: tile_anim, the font, the DAC as loaded at start, the backdrops'
colours, the fire's cycle, the line maps and the text styles.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from artlayout import TILES, SPRITES  # noqa: E402
from png import Image  # noqa: E402
import vgapal as V  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
VGA = os.path.join(ROOT, "gfx", "vga")
POWERUPS = ("fire", "bombup", "speed", "kick", "glove")


def load(name):
    img = Image(os.path.join(VGA, name))
    assert img.idx is not None, f"{name}: not an indexed PNG"
    return img


def block(img, x0, y0, w, h):
    return [img.idx[y0 + y][x0 + x] for y in range(h) for x in range(w)]


def tiles():
    img = load("tiles.png")
    frames, anim = [], []
    for i, name in enumerate(TILES):
        mine = []
        for f in range(4):
            px = block(img, f * 16, i * 16, 16, 16)
            if f and not any(px):
                break                   # an empty column: no more frames
            mine.append(len(frames))
            frames.append(px)
        n = len(mine)
        if n == 1:
            order = [0, 0, 0, 0]
        elif n == 2:
            order = [0, 0, 1, 1] if name in POWERUPS else [0, 1, 0, 1]
        elif n == 4:
            order = [0, 1, 2, 3]
        else:
            raise ValueError(f"{name}: {n} frames")
        anim.append([mine[k] for k in order])
    return frames, anim


def codes(name, w, h, nframes):
    """Seat 0's row, as codes; the other rows must be the same codes."""
    img = load(name)
    out = []
    for f in range(nframes):
        rows = []
        for seat in range(4):
            px = block(img, f * w, seat * h, w, h)
            base = V.SEAT + 16 * seat
            c = [0 if p == 0 else p - base for p in px]
            assert all(0 <= v < 16 for v in c), f"{name} frame {f} seat {seat}: not that seat's entries"
            rows.append(c)
        assert all(r == rows[0] for r in rows), f"{name} frame {f}: the seats differ"
        out.append(rows[0])
    return out


def flat(name, data, per=16):
    out = [f"{name} = {{"]
    for i in range(0, len(data), per):
        out.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + per]) + ",")
    out.append("};")
    return "\n".join(out)


def carray(name, rows):
    out = [f"{name} = {{"]
    for r in rows:
        out.append("    { " + ", ".join(f"0x{b:02X}" for b in r) + " },")
    out.append("};")
    return "\n".join(out)


def dac(colours):
    return [v for c in colours for v in V.to6(c)]


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "gen", "msdosvga")
    os.makedirs(out, exist_ok=True)
    frames, anim = tiles()
    cells = load("cells.png")
    cell = [block(cells, i * 8, 0, 8, 8) for i in range(2)]
    icons = load("icons.png")
    icon = [block(icons, i * 16, 0, 16, 16) for i in range(len(POWERUPS))]
    tro = block(load("trophy.png"), 0, 0, 16, 16)
    lg = load("logo.png")
    logo = block(lg, 0, 0, lg.width, lg.height)
    spr = codes("sprites.png", 16, 16, len(SPRITES))
    big = codes("bigwin.png", 32, 32, 2)
    font = open(os.path.join(ROOT, "gfx", "namco.bin"), "rb").read()
    assert len(font) == 768

    parts = [("A_TILES", [b for f in frames for b in f]), ("A_CELLS", [b for c in cell for b in c]),
             ("A_ICONS", [b for c in icon for b in c]), ("A_TROPHY", tro), ("A_LOGO", logo),
             ("A_SPR", [b for f in spr for b in f]), ("A_BIG", [b for f in big for b in f])]
    art, offs = [], {}
    for name, data in parts:
        offs[name] = len(art)
        art += data
    assert len(art) < 65520, len(art)

    pal = V.palette()
    styles = [V.STYLES[i] for i in range(len(V.STYLES))]

    h = ["/* GENERATED by tools/mkgfx_vga.py from gfx/vga/*.png and tools/vgapal.py: do not edit. */",
         "#ifndef GFXCODES_H", "#define GFXCODES_H", "#include <stdint.h>", ""]
    for i, name in enumerate(SPRITES):
        h.append(f"#define FR_{name.upper():8s} {i}")
    h += ["",
          f"#define N_SPR_FRAMES {len(SPRITES)}",
          f"#define N_TFRAMES    {len(frames)}",
          f"#define T_TROPHY     {TILES.index('trophy')}",
          f"#define N_TGFX       {len(TILES)}",
          f"#define LOGO_W       {lg.width}",
          f"#define LOGO_H       {lg.height}",
          ""]
    for name, _ in parts:
        h.append(f"#define {name:9s} {offs[name]}u")
    h += [f"#define ART_SIZE  {len(art)}u", "",
          "/* the DAC's entries (tools/vgapal.py) */",
          f"#define E_SEAT    {V.SEAT}",
          f"#define E_FIRE    {V.FIRE}",
          f"#define E_BACK    {V.BACK}",
          f"#define N_STYLES  {len(styles)}",
          f"#define ST_SILVER {V.ST_SILVER}",
          f"#define ST_GOLD   {V.ST_GOLD}",
          f"#define ST_SEAT   {V.ST_SEAT}",
          f"#define ST_INV    {V.ST_INV}",
          "",
          "extern const uint8_t __far gfx_art[ART_SIZE];",
          "extern const uint8_t tile_anim[N_TGFX][4];",
          "extern const uint8_t font_gfx[768];",
          "extern const uint8_t dac_init[768];         /* 6 bits a channel */",
          "extern const uint8_t back_title[96];        /* the 32 backdrop colours */",
          "extern const uint8_t back_menu[96];",
          "extern const uint8_t fire_cyc[4][48];       /* the fire's 16 colours, each phase */",
          "extern const uint8_t line_menu[200];        /* each line's backdrop entry */",
          "extern const uint8_t line_arena[200];",
          "extern const uint8_t text_style[N_STYLES][8];   /* a colour a glyph line */",
          "extern const uint8_t inv_bar[8];            /* ST_INV's background */",
          "", "#endif", ""]
    open(os.path.join(out, "gfxcodes.h"), "w").write("\n".join(h))

    c = ["/* GENERATED by tools/mkgfx_vga.py from gfx/vga/*.png, tools/vgapal.py and gfx/namco.bin: do not edit. */",
         "#include <stdint.h>", '#include "gfxcodes.h"', "",
         flat("const uint8_t __far gfx_art[ART_SIZE]", art, 32), "",
         carray("const uint8_t tile_anim[N_TGFX][4]", anim), "",
         flat("const uint8_t font_gfx[768]", list(font)), "",
         flat("const uint8_t dac_init[768]", dac(pal), 24), "",
         flat("const uint8_t back_title[96]", dac(V.TITLE_BACK), 24), "",
         flat("const uint8_t back_menu[96]", dac(V.MENU_BACK), 24), "",
         carray("const uint8_t fire_cyc[4][48]", [dac(V.fire_phase(p)) for p in range(4)]), "",
         flat("const uint8_t line_menu[200]", V.MENU_LINE, 20), "",
         flat("const uint8_t line_arena[200]", V.ARENA_LINE, 20), "",
         carray("const uint8_t text_style[N_STYLES][8]", styles), "",
         flat("const uint8_t inv_bar[8]", V.INV_BAR), ""]
    open(os.path.join(out, "gfxdata.c"), "w").write("\n".join(c))
    print(f"{out}: {len(frames)} tile frames, {len(SPRITES)} sprite frames, art {len(art)} bytes")


if __name__ == "__main__":
    main()
