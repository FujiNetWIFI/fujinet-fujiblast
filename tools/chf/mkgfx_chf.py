#!/usr/bin/env python3
"""mkgfx_chf.py -- gfx/channelf/*.png (tools/chf/drawart_chf.py) as the
Channel F build's tables, and what each costs in pixel writes.

    mkgfx_chf.py GFXDIR OUT.inc [--report]

OUT.inc goes in the data page, which START copies to RAM (DATA):
  TART    each tile frame, 30 bytes (6 x 5, rows), port-1 codes CV0-CV3
  TFOFF   each tile frame's address, big-endian (hi, lo)
  TKIND   each tile kind: its first frame, its frame count
  SART    each bomber frame, 30 bytes: $FF clear, 1 body, CV0 the visor
  SFOFF   each bomber frame's address
  TTX/TTY each tile's top-left pixel (0-142)
  (xypx.inc beside it, for the fixed ROM, page-aligned: XPX/YPX, a
          position in units (0-192, 0-160) as pixels from the arena's corner)

The console writes a pixel at a time (~180 clocks), so the art is held to
budgets: a bomber's 1-pixel step, a walk frame's change, a tile's
animation step. The build fails past them (--report prints every count).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))
from png import Image  # noqa: E402
from artlayout import TILES, SPRITES  # noqa: E402

TW, TH = 6, 5
AX0, AY0 = 8, 5
ROLE_RGB = {(224, 224, 224): 0, (75, 63, 243): 1, (255, 49, 83): 2, (2, 204, 93): 3}
CODE = {0: 0xC0, 1: 0x80, 2: 0x40, 3: 0x00}
FRAMES = {"burn": 2, "bomb": 4, "dud": 4, "fire": 2, "bombup": 2, "speed": 2,
          "kick": 2, "glove": 2}
for k in "CHVLRUD":
    FRAMES["flame" + k] = 2

# budgets: pixels a change may write
MOVE_MAX = 14       # a bomber's 1-pixel step across, same frame
MOVE_MAX_V = 20     # and up or down (each visor column changes twice)
FLIP_MAX = 6        # the next walk frame, in place
ANIM_MAX = 6        # a tile's next animation frame
ANIM_C_MAX = 10     # the blast's centre (both cores)


def tiles(gfx):
    img = Image(os.path.join(gfx, "tiles.png"))
    out = []
    for i, name in enumerate(TILES):
        frames = []
        for f in range(FRAMES.get(name, 1)):
            fr = []
            for y in range(TH):
                row = []
                for x in range(TW):
                    rgb = tuple(img.getpixel((f * TW + x, i * TH + y))[:3])
                    row.append(ROLE_RGB[rgb])
                fr.append(row)
            frames.append(fr)
        out.append((name, frames))
    return out


def sprites(gfx):
    img = Image(os.path.join(gfx, "sprites.png"))
    out = []
    for i, name in enumerate(SPRITES):
        fr = []
        for y in range(TH):
            row = []
            for x in range(TW):
                p = img.getpixel((i * TW + x, y))
                if len(p) > 3 and p[3] == 0:
                    row.append(".")
                elif tuple(p[:3]) == (255, 255, 255):
                    row.append("#")
                else:
                    row.append("v")
            fr.append(row)
        out.append((name, fr))
    return out


def shift_delta(fr, dx, dy):
    """Pixels that change when the frame moves by (dx, dy): clear shows BG."""
    def at(x, y):
        if 0 <= x < TW and 0 <= y < TH:
            return fr[y][x]
        return "."
    n = 0
    for y in range(-1, TH + 1):
        for x in range(-1, TW + 1):
            if at(x, y) != at(x - dx, y - dy):
                n += 1
    return n


def diff(a, b):
    return sum(1 for y in range(TH) for x in range(TW) if a[y][x] != b[y][x])


def main():
    gfx, out = sys.argv[1], sys.argv[2]
    report = "--report" in sys.argv
    tl = tiles(gfx)
    sp = sprites(gfx)
    errs = []
    L = ["; GENERATED by tools/chf/mkgfx_chf.py from gfx/channelf -- do not edit."]
    # the tile frames
    L.append("TART:")
    nfr = 0
    kinds = []
    for name, frames in tl:
        kinds.append((nfr, len(frames)))
        for f in frames:
            L.append("        DB " + ",".join("0%02XH" % CODE[v] for row in f for v in row)
                     + "  ; %s" % name)
            nfr += 1
        cost = sum(1 for row in frames[0] for v in row if v)
        anims = [diff(frames[k], frames[(k + 1) % len(frames)]) for k in range(len(frames))] if len(frames) > 1 else []
        cap = ANIM_C_MAX if name == "flameC" else ANIM_MAX
        if report:
            print("tile %-8s from floor %2d  steps %s" % (name, cost, anims))
        if name not in ("burn",) and any(a > cap for a in anims):
            errs.append("tile %s: an animation step writes %d pixels (budget %d)" % (name, max(anims), cap))
    L.append("TFOFF:")
    for n in range(nfr):
        L.append("        DB (TART+%d)>>8, (TART+%d)&0FFH" % (30 * n, 30 * n))
    L.append("TKIND:")
    for first, count in kinds:
        L.append("        DB %d, %d" % (first, count))
    # the bomber frames
    L.append("SART:")
    rolebyte = {".": "0FFH", "#": "1", "v": "0C0H"}
    for name, fr in sp:
        L.append("        DB " + ",".join(rolebyte[c] for row in fr for c in row) + "  ; %s" % name)
        moves = [shift_delta(fr, dx, dy) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))]
        if report:
            print("bomber %-7s step R L D U %s" % (name, moves))
        if not name.startswith(("die", "win")) and (max(moves[:2]) > MOVE_MAX or max(moves[2:]) > MOVE_MAX_V):
            errs.append("bomber %s: a 1-pixel step writes %s pixels (budget %d across, %d down)"
                        % (name, moves, MOVE_MAX, MOVE_MAX_V))
    names = [n for n, _ in sp]
    for d in ("down", "up", "right", "left"):
        for k in range(3):
            a, b = dict(sp)[d + str(k)], dict(sp)[d + str((k + 1) % 3)]
            n = diff(a, b)
            if report:
                print("walk %s%d -> %s%d: %d" % (d, k, d, (k + 1) % 3, n))
            if n > FLIP_MAX:
                errs.append("walk %s%d -> %d: %d pixels (budget %d)" % (d, k, (k + 1) % 3, n, FLIP_MAX))
    L.append("SFOFF:")
    for n in range(len(names)):
        L.append("        DB (SART+%d)>>8, (SART+%d)&0FFH" % (30 * n, 30 * n))
    # where each tile sits; units to pixels
    L.append("TTX:")
    for r in range(0, 143, 13):
        L.append("        DB " + ",".join(str(AX0 + TW * (t % 13)) for t in range(r, min(r + 13, 143))))
    L.append("TTY:")
    for r in range(0, 143, 13):
        L.append("        DB " + ",".join(str(AY0 + TH * (t // 13)) for t in range(r, min(r + 13, 143))))
    # units to pixels: in the fixed ROM, page-aligned (a lookup is (hi, x))
    X = ["; GENERATED by tools/chf/mkgfx_chf.py -- do not edit.",
         "        ALIGN 256",
         "XPX:"]
    xs = [x * TW // 16 for x in range(193)]
    for i in range(0, len(xs), 16):
        X.append("        DB " + ",".join(str(v) for v in xs[i:i + 16]))
    X.append("        DB 256 - 193 DUP (0)")
    X.append("YPX:")
    ys = [y * TH // 16 for y in range(161)]
    for i in range(0, len(ys), 16):
        X.append("        DB " + ",".join(str(v) for v in ys[i:i + 16]))
    open(os.path.join(os.path.dirname(out), "xypx.inc"), "w").write("\n".join(X) + "\n")
    open(out, "w").write("\n".join(L) + "\n")
    for e in errs:
        print("mkgfx_chf: " + e, file=sys.stderr)
    if errs:
        sys.exit(1)


if __name__ == "__main__":
    main()
