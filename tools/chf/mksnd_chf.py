#!/usr/bin/env python3
"""mksnd_chf.py -- FujiBlast's sounds for the Channel F's three tones.

    mksnd_chf.py src/apple2/sndtab.s OUT.inc

The console has port 5 bits 7-6 for sound: 1 kHz, 500 Hz (an octave
apart) and a 120 Hz buzz, no volume; a tone rings and decays in about 9 ms
unless struck again, and it is struck only when the bits change. So a sound
here is a list of steps, each (tone, jiffies, strike): the tone held for its
jiffies, struck again every jiffy (2: every other one, 0: once). A jingle is
its melody's rhythm and shape: the notes from G5 up on the high tone, the
rest on the mid one, a 2-jiffy gap before each (so a repeated note is heard
again). The effects are drawn by hand after the Atari's (sndtab.s).

OUT.inc: SNDTAB, each sound's address (hi, lo) by id (sound.inc's SND_*,
MUS_*), then the lists: DB tone, jiffies, strike ... DB 0, 0, 0.
"""
import re
import sys

HI, MID, BUZZ, OFF = 0x40, 0x80, 0xC0, 0x00
NOTES = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}

# the effects: (tone, jiffies, strike)
EFFECTS = {
    "s_drop": [(MID, 2, 0), (OFF, 1, 0), (MID, 2, 0)],
    "s_boom": [(BUZZ, 10, 1), (BUZZ, 10, 2), (BUZZ, 8, 0)],
    "s_pickup": [(MID, 3, 0), (HI, 3, 0), (MID, 3, 0), (HI, 6, 1)],
    "s_kick": [(BUZZ, 2, 0), (MID, 2, 0)],
    "s_throw": [(BUZZ, 2, 0), (MID, 3, 0), (HI, 3, 0)],
    "s_fizzle": [(BUZZ, 3, 0), (OFF, 3, 0), (BUZZ, 3, 0), (OFF, 3, 0), (BUZZ, 4, 0)],
    "s_die": [(HI, 6, 1), (MID, 8, 1), (BUZZ, 14, 2)],
    "s_beep": [(HI, 5, 1)],
    "s_go": [(MID, 6, 1), (HI, 14, 1)],
    "s_select": [(HI, 1, 0)],
}
ORDER = ["s_drop", "s_boom", "s_pickup", "s_kick", "s_throw", "s_fizzle", "s_die",
         "s_beep", "s_go", "s_select", "m_title", "m_round", "m_win", "m_game"]


def semis(name):
    return NOTES[name[0]] + 12 * int(name[-1])


def jingles(src):
    """The N/R lines of sndtab.s's m_* sounds: [(name or None, jiffies)]."""
    out, cur = {}, None
    for line in open(src):
        line = line.split(";", 1)[0].rstrip()
        m = re.match(r"^_(m_\w+):\s*(.*)$", line)
        if m:
            cur = m.group(1)
            out[cur] = []
            line = m.group(2)
        if cur is None:
            continue
        s = line.strip()
        op, _, args = s.partition(" ")
        a = [x.strip() for x in args.split(",") if x.strip()]
        if op == "N":
            out[cur].append((a[0], int(a[1])))
        elif op == "R":
            out[cur].append((None, int(a[0])))
        elif op == "END":
            cur = None
    return out


def melody(items):
    steps = []
    g5 = semis("G5")
    for name, ln in items:
        if name is None:
            steps.append((OFF, ln, 0))
            continue
        tone = HI if semis(name) >= g5 else MID
        steps.append((OFF, 2, 0))
        steps.append((tone, max(1, ln - 2), 2))
    return steps


def main(src, out):
    jg = jingles(src)
    sounds = dict(EFFECTS)
    for k in ("m_title", "m_round", "m_win", "m_game"):
        sounds[k] = melody(jg[k])
    L = ["; GENERATED by tools/chf/mksnd_chf.py from src/apple2/sndtab.s -- do not edit.",
         "SNDTAB:"]
    for k in ORDER:
        L.append("        DB (SND_%s)>>8, (SND_%s)&0FFH" % (k, k))
    for k in ORDER:
        L.append("SND_%s:" % k)
        for t, n, st in sounds[k]:
            L.append("        DB 0%02XH, %d, %d" % (t, n, st))
        L.append("        DB 0, 0, 0")
    open(out, "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main(*sys.argv[1:3])
