#!/usr/bin/env python3
"""mkmus_dos.py -- FujiBlast's in-play music (music/play.txt, tools/mus.py)
for the PC speaker (src/msdos/sound.c, mus_step). The speaker has one voice,
so only ch1 is played: the bass, and the drums (kick a falling thump, snare
and hat noise).

A step is a PIT divisor (1193182 / Hz) and jiffies (1-255):

    d = 0           a rest
    d & 0x8000      noise: the divisor (d & 0x7FFF) wanders each jiffy
    d               a tone

Each pattern's ch1 is a deduplicated array ending {0, 0}; m_order lists the
patterns, m_loopat is the one the song goes back to.

usage: mkmus_dos.py music/play.txt OUTDIR [OCTAVES]   (writes OUTDIR/music.c)
OCTAVES shifts the bass up (default 1: E1 is 41 Hz, hard to hear on a
speaker)."""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mus  # noqa: E402

PIT = 1193182.0
NOISE = 0x8000
MAXN = 255
# noise centre (Hz): the interrupt spreads it 0.5-1.5x
SNARE_HZ, HAT_HZ = 1200.0, 4500.0
KICK_HZ = (150.0, 70.0)


def div(hz):
    return round(PIT / hz)


def voice(ev, octaves):
    if ev is None:
        return 0
    kind, note, k = ev
    if kind == "K":
        return div(KICK_HZ[min(k, 1)])
    if kind == "S":
        return NOISE | div(SNARE_HZ)
    if kind == "H":
        return NOISE | div(HAT_HZ)
    if kind == "bass":
        return div(mus.hz(note) * 2 ** octaves)
    raise SystemExit("no ch1 voice for %r" % kind)


def steps(evs, octaves):
    out = []
    for d in (voice(e, octaves) for e in evs):
        if out and out[-1][0] == d and out[-1][1] < MAXN:
            out[-1][1] += 1
        else:
            out.append([d, 1])
    return out


def main():
    src, outdir = sys.argv[1], sys.argv[2]
    octaves = int(sys.argv[3]) if len(sys.argv) > 3 else 1
    song = mus.parse(src)
    subs, order = {}, []
    for name in song.order:
        key = tuple(map(tuple, steps(mus.frames(song, name, 1), octaves)))
        if key not in subs:
            subs[key] = "m_%d" % len(subs)
        order.append(subs[key])

    lines = ["/* GENERATED by tools/mkmus_dos.py from %s: edit that, not this. */" % src,
             "#ifdef __MSDOS__", "#include <stdint.h>", "#include \"sound.h\"", ""]
    size = 0
    for key, lab in subs.items():
        lines.append("static const MusStep %s[] = {" % lab)
        for d, n in key:
            lines.append("    { 0x%04X, %d }," % (d, n))
        lines.append("    { 0, 0 },")
        lines.append("};")
        size += 3 * (len(key) + 1)
    lines.append("")
    lines.append("const MusStep *const m_order[] = { %s };" % ", ".join(order))
    lines.append("const uint8_t m_count = %d, m_loopat = %d;" % (len(order), song.loop))
    lines.append("#endif")
    size += 2 * len(order)
    os.makedirs(outdir, exist_ok=True)
    with open(os.path.join(outdir, "music.c"), "w") as f:
        f.write("\n".join(lines) + "\n")

    jiffies = sum(len(song.patterns[n]) for n in song.order) * song.tempo
    print("music: %d bars, %.1f s a loop at 60 Hz, %d bytes, %d subroutines, bass %+d octave"
          % (len(order), jiffies / 60, size, len(subs), octaves))
    used = sorted({ev[1] for n in song.order for ev in mus.frames(song, n, 1)
                   if ev and ev[0] == "bass"})
    names = "C C# D Eb E F F# G G# A Bb B".split()
    out = []
    for n in used:
        want = mus.hz(n) * 2 ** octaves
        d = div(want)
        got = PIT / d
        out.append("%s%d d=%d %+.1fc" % (names[n % 12], n // 12 - 1 + octaves, d,
                                        1200 * math.log2(got / want)))
    print("bass: " + ", ".join(out))


if __name__ == "__main__":
    main()
