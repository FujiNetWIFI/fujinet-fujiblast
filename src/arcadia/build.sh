#!/usr/bin/env bash
# build.sh -- FujiBlast for the Emerson Arcadia 2001: a protocol 2 (APPBANK)
# image -- page 0's 8K (fixed A, RAM-L, fixed B, RAM-H; the mailbox empty and
# claimed) and NPAGES-1 more pages of 2K. The page model, the linker and the
# checks are M.U.L.E.'s clients/arcadia (tools/arc/).
#
#   src/arcadia/build.sh                r2r/arcadia/fujiblst.bin
#   OUT=dir R2R=dir                     where the objects and the image go
#   DEFSRV=host:port                    the server without the lobby's key
#                                       (default gen/server, never rewritten here)
#   LOOK=n                              the arena's colours (src/look.inc)
#
# Needs Macroassembler AS (~/asl/asl and p2bin, or ASL=/P2BIN=).
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
OUT="${OUT:-$ROOT/build/arcadia}"
R2R="${R2R:-$ROOT/r2r/arcadia}"
ASL="${ASL:-$HOME/asl/asl}"
P2BIN="${P2BIN:-$HOME/asl/p2bin}"
T="$ROOT/tools/arc"
mkdir -p "$OUT" "$R2R"

python3 "$ROOT/tools/o2/mkproto.py" "$ROOT/src/proto.h" "$OUT/proto.inc"
python3 "$T/mkgfx_arc.py" "$ROOT/gfx/arcadia" "$OUT/art.inc" "$OUT/artequ.inc" "$OUT/logo.inc"
python3 "$T/mksnd_arc.py" "$OUT/snd.inc"
python3 "$T/mkcanned.py" "$ROOT/src/proto.h" "$OUT/canned.inc"
DEFSRV="${DEFSRV:-$(cat "$ROOT/gen/server" 2>/dev/null || echo fujinet.online:9910)}"
{
  echo "; GENERATED by build.sh -- do not edit."
  printf 'DEFSPEC: DB      "N:TCP://%s/",0\n' "$DEFSRV"
  printf 'DEFURL:  DB      "tcp://%s/?table=",0\n' "$DEFSRV"
} > "$OUT/config.inc"
{
  echo "; GENERATED by build.sh -- do not edit."
  [ -n "${LOOK:-}" ] && echo "LOOK EQU ${LOOK}"
  true
} > "$OUT/flags.inc"
NPAGES=$(sed -n 's/^NPAGES *EQU *\([0-9]*\).*/\1/p' "$HERE/src/pages.inc")

for p in $(seq 0 $((NPAGES - 1))); do
    printf '; GENERATED by build.sh -- do not edit.\nPAGE EQU %d\n        INCLUDE "fujiblst.asm"\n' "$p" \
        > "$OUT/fb_p$p.asm"
    "$ASL" -q -L -U -i "$HERE" -i "$OUT" -o "$OUT/fb_p$p.p" -olist "$OUT/fb_p$p.lst" "$OUT/fb_p$p.asm"
    "$P2BIN" "$OUT/fb_p$p.p" "$OUT/fb_p$p.flat" -r '$0000-$2FFF' -l 0 >/dev/null
done
python3 "$T/mkblast.py" "$OUT" fb "$NPAGES" "$R2R/fujiblst.bin"
# the 2650's return stack is 8 deep and silently wraps: keep one spare
python3 "$T/checkdepth.py" --max 7 "$HERE/src/pages.inc" "$OUT"/fb_p*.lst
# a register read after a cart-RAM write (or another clobbering service)
python3 "$T/checkclob.py" "$HERE"/src/*.inc
# a conditional branch testing a LODI's constant
python3 "$T/checkcc.py" "$HERE"/src/*.inc
