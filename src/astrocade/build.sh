#!/usr/bin/env bash
# build.sh -- FujiBlast for the Bally Astrocade: a protocol 2 (APPBANK)
# image -- the 8K window (page 0, the resident half, the mailbox clear and
# claimed) and NPAGES-2 more pages of 4K (fujiblst.asm). M.U.L.E.'s
# clients/astrocade build, for this tree.
#
#   src/astrocade/build.sh              r2r/astrocade/fujiblst.bin
#   OUT=dir R2R=dir                     where the objects and the image go
#   DEFSRV=host:port                    the server without the lobby's key
#                                       (default gen/server, never rewritten here)
#   LOOK=n                              the arena's colours (src/look.inc)
#
# Needs zmac 1.3's source (~/Workspace/zmac-1.3, or ZMACSRC=): zmac holds
# 2000 symbols and this program has more, so the build makes its own copy
# with a bigger table (build/zmac/zmac).
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
OUT="${OUT:-$ROOT/build/astrocade}"
R2R="${R2R:-$ROOT/r2r/astrocade}"
T="$ROOT/tools/astro"
mkdir -p "$OUT" "$R2R"
OUT="$(cd "$OUT" && pwd)"

ZMAC="${ZMAC:-$ROOT/build/zmac/zmac}"
if [ ! -x "$ZMAC" ]; then
    src=""
    for d in "${ZMACSRC:-}" "$HOME/Workspace/zmac-1.3" "$HOME/Workspace/fujinet-firmware/pico/astrocade/tools/zmac"; do
        if [ -n "$d" ] && [ -f "$d/zmac.c" ] && [ -f "$d/mio.c" ]; then src="$d"; break; fi
    done
    [ -n "$src" ] || { echo "build.sh: no zmac 1.3 source; set ZMACSRC=" >&2; exit 1; }
    mkdir -p "$ROOT/build/zmac/src"
    cp "$src"/*.c "$src"/*.h "$ROOT/build/zmac/src/"
    sed -i 's/^#define ITEMTABLESIZE.*/#define ITEMTABLESIZE 16000/' "$ROOT/build/zmac/src/zmac.c"
    (cd "$ROOT/build/zmac/src" && gcc -O -o ../zmac zmac.c mio.c getoptn.c)
fi

python3 "$ROOT/tools/o2/mkproto.py" "$ROOT/src/proto.h" "$OUT/proto.inc"
python3 "$T/mkgfx_astro.py" "$ROOT/gfx/astrocade" "$OUT/art.inc" "$OUT/artequ.inc" "$OUT/logo.inc" "$OUT/icon.inc"
python3 "$T/mksnd_astro.py" "$ROOT/src/apple2/sndtab.s" "$OUT/snd.inc"
python3 "$T/mkcanned.py" "$ROOT/src/proto.h" "$OUT/canned.inc"
DEFSRV="${DEFSRV:-$(cat "$ROOT/gen/server" 2>/dev/null || echo fujinet.online:9910)}"
{
  echo "; GENERATED by build.sh -- do not edit."
  printf 'DEFSPEC: DB      "N:TCP://%s/",0\n' "$DEFSRV"
  printf 'DEFURL:  DB      "tcp://%s/?table=",0\n' "$DEFSRV"
} > "$OUT/config.inc"
{
  echo "; GENERATED by build.sh -- do not edit."
  echo "LOOK    EQU     ${LOOK:-0}"
  echo "FOOTER  EQU     ${FOOTER:-1}"
} > "$OUT/flags.inc"

ln -sfn "$HERE" "$OUT/srcdir"
(cd "$OUT" && "$ZMAC" -o fujiblst.raw -x fujiblst.lst srcdir/fujiblst.asm)
if grep -q "^[0-9]* errors" "$OUT/fujiblst.lst" && ! grep -q "^0 errors" "$OUT/fujiblst.lst"; then
    grep -B2 -A2 "^[A-Za-z] " "$OUT/fujiblst.lst" | head -40 >&2
    echo "build.sh: zmac reported errors (see $OUT/fujiblst.lst)" >&2
    exit 1
fi

# the image: 8K + (NPAGES-2) x 4K (page 1 is the window's high half)
npages=$(sed -n 's/^NPAGES *EQU *\([0-9]*\).*/\1/p' "$HERE/src/pages.inc")
IMAGE=$((8192 + (npages - 2) * 4096))
size=$(wc -c < "$OUT/fujiblst.raw")
if [ "$size" -gt "$IMAGE" ]; then
    echo "build.sh: the assembly is $size bytes, over the $IMAGE image" >&2
    exit 1
fi
{
    cat "$OUT/fujiblst.raw"
    head -c $((IMAGE - size)) /dev/zero
} > "$R2R/fujiblst.bin"
printf 'FUJI' | dd of="$R2R/fujiblst.bin" bs=1 seek=$((0x1CFC)) conv=notrunc status=none

python3 "$T/checkrom.py" --banked "$R2R/fujiblst.bin"
python3 "$T/checksize.py" "$OUT/fujiblst.lst"
python3 "$T/checkcalls.py" "$OUT/fujiblst.lst"
