#!/usr/bin/env bash
# build.sh -- FujiBlast for the Fairchild Channel F: a protocol 2 (APPBANK)
# image -- the fixed 16K and six 8K pages, 64K (fujiblst.asm). M.U.L.E.'s
# clients/channelf build, for this tree.
#
#   src/channelf/build.sh               r2r/channelf/fujiblst.bin
#   OUT=dir R2R=dir                     where the objects and the image go
#   DEFSRV=host:port                    the server without the lobby's key
#                                       (default gen/server, never rewritten here)
#   LOOK=n                              the arena's colours (p_arena.inc): 0 grey
#                                       floor (default), 1 green, 2 blue
#   SETTLE=mule|bios|N                  clocks after a VRAM strobe before the next
#                                       port write: 94 (M.U.L.E.'s, default) or
#                                       136 (the BIOS's)
#   ASL=, P2BIN=                        the assembler (default ~/asl)
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
OUT="${OUT:-$ROOT/build/channelf}"
R2R="${R2R:-$ROOT/r2r/channelf}"
T="$ROOT/tools/chf"
ASL="${ASL:-$HOME/asl/asl}"
P2BIN="${P2BIN:-$HOME/asl/p2bin}"
[ -x "$ASL" ]   || { echo "build.sh: no assembler at $ASL" >&2; exit 1; }
[ -x "$P2BIN" ] || { echo "build.sh: no p2bin at $P2BIN" >&2; exit 1; }
mkdir -p "$OUT" "$R2R"
OUT="$(cd "$OUT" && pwd)"

case "${SETTLE:-mule}" in
    mule) settle=94 ;;
    bios) settle=136 ;;
    *)    settle="$SETTLE" ;;
esac

python3 "$ROOT/tools/o2/mkproto.py" "$ROOT/src/proto.h" "$OUT/proto.inc"
python3 "$T/mkgfx_chf.py" "$ROOT/gfx/channelf" "$OUT/art.inc"
python3 "$T/mkfont.py" "$OUT/font.inc"
python3 "$T/mkcanned.py" "$ROOT/src/proto.h" "$OUT/canned.inc"
python3 "$T/mksnd_chf.py" "$ROOT/src/apple2/sndtab.s" "$OUT/snd.inc"
DEFSRV="${DEFSRV:-$(cat "$ROOT/gen/server" 2>/dev/null || echo fujinet.online:9910)}"
{
  echo "; GENERATED by build.sh -- do not edit."
  printf 'DEFSPEC: DB "N:TCP://%s/",0\n' "$DEFSRV"
  printf 'DEFURL:  DB "tcp://%s/?table=",0\n' "$DEFSRV"
} > "$OUT/config.inc"
{
  echo "; GENERATED by build.sh -- do not edit."
  echo "LOOK    EQU ${LOOK:-0}"
  echo "SETTLE  EQU $settle"
  echo "DEBUG   EQU ${DEBUG:-0}"
} > "$OUT/flags.inc"

ln -sfn "$HERE" "$OUT/srcdir"
(cd "$OUT" && "$ASL" srcdir/fujiblst.asm -L -i . -q -o fujiblst.p -olist fujiblst.lst) || {
    grep -B1 -A3 "Error\|error" "$OUT/fujiblst.lst" | head -40 >&2
    echo "build.sh: asl failed (see $OUT/fujiblst.lst)" >&2
    exit 1
}
"$P2BIN" "$OUT/fujiblst.p" "$R2R/fujiblst.bin" -r 0x0000-0xffff -l 0xff -q
rm -f "$OUT/fujiblst.p"

python3 "$T/checkrom.py" "$R2R/fujiblst.bin"
python3 "$T/checksize.py" "$OUT/fujiblst.lst"
python3 "$T/checkcalls.py" "$HERE/src"
python3 "$T/checkacc.py" "$HERE"/src/*.inc "$HERE/fujiblst.asm"
