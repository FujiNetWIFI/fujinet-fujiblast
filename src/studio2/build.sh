#!/usr/bin/env bash
# build.sh -- FujiBlast for the RCA Studio II: an ST2 image for the FujiNet
# cart's protocol 2 (fujiblst.asm). M.U.L.E.'s clients/studio2 build, for
# this tree.
#
#   src/studio2/build.sh                r2r/studio2/fujiblst.st2
#   OUT=dir R2R=dir                     where the objects and the image go
#   DEFSRV=host:port                    the server without the lobby's key
#                                       (default gen/server, never rewritten here)
#   DEBUG=1                             the rigs' extras (traces, counters)
#   ASL=                                the assembler (default ~/asl/asl)
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
OUT="${OUT:-$ROOT/build/studio2}"
R2R="${R2R:-$ROOT/r2r/studio2}"
T="$ROOT/tools/s2"
ASL="${ASL:-$HOME/asl/asl}"
[ -x "$ASL" ] || ASL=$(command -v asl) || { echo "build.sh: no asl (Macroassembler AS)" >&2; exit 1; }
mkdir -p "$OUT" "$R2R"
OUT="$(cd "$OUT" && pwd)"

python3 "$ROOT/tools/o2/mkproto.py" "$ROOT/src/proto.h" "$OUT/proto.inc"
python3 "$T/mkart_s2.py" "$ROOT/gfx/studio2/art.txt" "$OUT"
python3 "$ROOT/tools/chf/mkcanned.py" "$ROOT/src/proto.h" "$OUT/canned.inc"
python3 "$T/mksnd_s2.py" "$ROOT/src/apple2/sndtab.s" "$OUT/snd.inc"
DEFSRV="${DEFSRV:-$(cat "$ROOT/gen/server" 2>/dev/null || echo fujinet.online:9910)}"
{
  echo "; GENERATED by build.sh -- do not edit."
  printf 'DEFSPEC: DB "N:TCP://%s/",0\n' "$DEFSRV"
  printf 'DEFURL:  DB "tcp://%s/?table=",0\n' "$DEFSRV"
} > "$OUT/config.inc"
{
  echo "; GENERATED by build.sh -- do not edit."
  echo "DEBUG   EQU ${DEBUG:-0}"
} > "$OUT/flags.inc"

(cd "$OUT" && "$ASL" -q -L -U -i "$HERE/rt" -i "$HERE/src" -i "$OUT" \
     -o fujiblst.p -olist fujiblst.lst "$HERE/fujiblst.asm") || {
    grep -B2 -A3 "Error\|error" "$OUT/fujiblst.lst" | head -40 >&2
    echo "build.sh: asl failed (see $OUT/fujiblst.lst)" >&2
    exit 1
}
python3 "$T/checkrom.py" "$OUT/fujiblst.lst"
python3 "$T/fitcheck.py" "$OUT/fujiblst.lst"
python3 "$T/checkldr.py" "$HERE"/src/*.inc
python3 "$T/mkst2.py" "$OUT/fujiblst.p" "$R2R/fujiblst.st2" "FUJIBLAST"
