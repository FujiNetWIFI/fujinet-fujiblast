#!/bin/bash
# build.sh -- FujiBlast for the Odyssey 2: a protocol 2 (APPBANK) image -- the
# fixed half ($400-$7FF) and NPAGES pages of 2K. The engine and its checks
# are the O2 lobby's and CONFIG's (tools/o2/).
#
#   src/o2/build.sh                     r2r/o2/fujiblst.bin
#   OUT=dir R2R=dir                     where the objects and the image go
#   GLEAD= GPREN= GNOPN= GPRENP= GNOPNP= LOOK= MIDL=
#                                       the arena's timing and look (equ.inc)
#
# Needs Macroassembler AS (~/asl/asl and p2bin, or ASL=/P2BIN=).
set -e
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
OUT="${OUT:-$ROOT/build/o2}"
R2R="${R2R:-$ROOT/r2r/o2}"
ASL="${ASL:-$HOME/asl/asl}"
P2BIN="${P2BIN:-$HOME/asl/p2bin}"
T="$ROOT/tools/o2"
NPAGES=12
PG_OV=3                         # the swap (p3.inc): built last
mkdir -p "$OUT" "$R2R"

python3 "$T/checkflags.py" "$HERE"/src/*.inc
python3 "$T/mkproto.py" "$ROOT/src/proto.h" "$OUT/proto.inc"
python3 "$T/mkgfx_o2.py" "$OUT/sprites.inc" "$OUT/sprfr.inc"
python3 "$T/mkcanned.py" "$ROOT/src/proto.h" "$OUT/canned.inc"
python3 "$T/mkcharmap.py" "$OUT/charmap.inc"
# The server used without the lobby's key: DEFSRV, else gen/server (the
# user's: never rewritten here), else fujinet.online:9910.
DEFSRV="${DEFSRV:-$(cat "$ROOT/gen/server" 2>/dev/null || echo fujinet.online:9910)}"
{
  echo "; GENERATED by build.sh -- do not edit."
  printf 'defspec: db "N:TCP://%s/",0\n' "$DEFSRV"
  printf 'defurl:  db "tcp://%s/?table=",0\n' "$DEFSRV"
} > "$OUT/config.inc"
{
  echo "; GENERATED by build.sh -- do not edit."
  for v in GLEAD GPREN GNOPN GLEADP GPRENP GNOPNP LOOK MIDL ARENA_COL; do
    [ -n "${!v:-}" ] && echo "$v equ ${!v}"
  done
  true
} > "$OUT/flags.inc"
cp "$HERE"/src/*.inc "$HERE/g7000.h" "$HERE/fujiblst.a48" "$HERE/arena.a48" "$OUT/"

# The arena's overlay on its own: its bytes for the swap, its symbols for
# the pages.
( cd "$OUT" && "$ASL" -q -L -U arena.a48 \
    && "$P2BIN" arena.p arena_ov.bin -r 0x600-0x7FF -l 0 >/dev/null \
    && "$P2BIN" arena.p arena_core.bin -r 0x400-0x5FF -l 0 >/dev/null )
python3 "$T/checkobj.py" "$OUT/arena.p"
python3 "$T/checkflags.py" "$OUT/arena.lst" >/dev/null 2>&1 || true
python3 "$T/symexp.py" "$OUT/arena.lst" "$OUT/arena_sym.inc" \
  GRIDROWS CAPNONE CAPPIL GW_PRE GW_NOP GO_PRE VB_FIRST BL_FIRSTP

# The pages, the swap's last: its overlay data is the text overlay out of
# the fixed half every page carries.
asm_page() {
  local p=$1
  printf '; GENERATED by build.sh -- do not edit.\nPAGE equ %d\nNPAGES equ %d\n    include "fujiblst.a48"\n' \
    "$p" "$NPAGES" > "$OUT/fb_p$p.a48"
  ( cd "$OUT" && "$ASL" -q -L -U "fb_p$p.a48" \
      && "$P2BIN" "fb_p$p.p" "fb_pg$p.bin" -r 0x800-0xFFF -l 0 >/dev/null \
      && "$P2BIN" "fb_p$p.p" "fb_fx$p.bin" -r 0x400-0x7FF -l 0 >/dev/null )
  python3 "$T/checkobj.py" "$OUT/fb_p$p.p"
  python3 "$T/checklayout.py" "$OUT/fb_p$p.lst"
  python3 "$T/checkmb.py" "$OUT/fb_p$p.lst" >/dev/null
  python3 "$T/checkpage.py" "$OUT/fb_p$p.lst"
}
echo "; (the swap's data: made after the other pages)" > "$OUT/ovdata.inc"
for p in $(seq 0 $((NPAGES-1))); do
  [ "$p" = "$PG_OV" ] || asm_page "$p"
done
head -c 512 "$OUT/fb_fx0.bin" | cmp -s - "$OUT/arena_core.bin" \
  || { echo "build.sh: arena.a48's core and state differ from the pages'" >&2; exit 1; }
tail -c 512 "$OUT/fb_fx0.bin" > "$OUT/text_ov.bin"
python3 "$T/mkovdata.py" "$OUT/ovdata.inc" 900 arena="$OUT/arena_ov.bin" text="$OUT/text_ov.bin"
asm_page "$PG_OV"
parts=""
for p in $(seq 0 $((NPAGES-1))); do
  # Every page carries the fixed half; they have to be the same bytes.
  cmp -s "$OUT/fb_fx0.bin" "$OUT/fb_fx$p.bin" \
    || { echo "build.sh: page $p assembled a different fixed half" >&2; exit 1; }
  parts="$parts $OUT/fb_pg$p.bin"
done
# The stack is 8 levels and wraps silently: interrupts plus the deepest main
# chain have to fit. Page 1 (the arena's drawing) is farcalled.
python3 "$T/checkstack.py" --far 1,3,4,5,6,9,10 $(for p in $(seq 0 $((NPAGES-1))); do echo "$OUT/fb_p$p.lst"; done) >/dev/null
cat "$OUT/fb_fx0.bin" $parts > "$R2R/fujiblst.bin"
size=$(wc -c < "$R2R/fujiblst.bin")
[ "$size" -eq $((1024 + 2048 * NPAGES)) ] \
  || { echo "build.sh: fujiblst.bin is $size bytes" >&2; exit 1; }
echo "${R2R#$ROOT/}/fujiblst.bin: $size bytes, $NPAGES pages"
